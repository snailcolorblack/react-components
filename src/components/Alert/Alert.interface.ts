// Alert.interface.ts
import type {ComponentPropsWithRef, ReactNode} from "react";

export type AlertVariant = 'SUCCESS' | 'WARNING' | 'ERROR';

/**
 * React 19: `ref` — обычный проп, forwardRef не требуется.
 */
export type AlertProps = ComponentPropsWithRef<"div"> & {
    /**
     * Важность сообщения.
     *
     * Показана цветом и словом в начале текста («Ошибка.»,
     * «Предупреждение.», «Готово.»). Слово скрыто от глаз и читается
     * только озвучкой; глазами важность видно по цвету, а со значком —
     * ещё и по нему.
     *
     * Одного цвета было бы мало: замерено, когда-то варианты различались
     * только им, а в режиме высокого контраста цвета подменяет система
     * и разница пропадает совсем (WCAG 1.4.1). Поэтому плашка без значка
     * в высоком контрасте показывает слово глазами.
     */
    variant?: AlertVariant;
    /**
     * Показать стандартный значок варианта: галочку у `SUCCESS`,
     * треугольник у `WARNING`, круг с крестом у `ERROR`. По умолчанию
     * значка нет.
     *
     * У форм разные силуэты не случайно: цвет в высоком контрасте
     * подменяет система, а форма остаётся.
     */
    withIcon?: boolean;
    /**
     * Свой значок вместо стандартного. Показывается сам по себе,
     * без `withIcon`: раз его передали, значок нужен.
     *
     * Декоративный: помечается `aria-hidden`, потому что повторяет слово,
     * которое и так читается озвучкой.
     */
    icon?: ReactNode;
    /**
     * Живой регион. По умолчанию `false`: сообщение считается статичным
     * и не зачитывается при первом рендере.
     * `true` — для сообщений, появляющихся в ответ на действие пользователя:
     * ERROR получает role="alert" (assertive), остальные — role="status" (polite).
     *
     * Важно, КАК его показывать. `role="alert"` объявляется и тогда, когда
     * узел добавили в разметку вместе с текстом. А вот `role="status"`
     * (polite) так объявляется не всегда: живая область должна существовать
     * заранее, а меняться должно только её содержимое. То есть для не-ошибок
     * держите `<Alert live>` в разметке постоянно и меняйте детей, а не
     * монтируйте его вместе с сообщением.
     */
    live?: boolean;
};
