// Alert.tsx

/* -------------------------------------------------------------------------- */
/*  РАБОТА С ПЛАШКОЙ                                                          */
/*                                                                            */
/*  Alert решает две разные задачи, и выбирает между ними проп live:           */
/*  оформить уже существующий на странице текст — или объявить сообщение,      */
/*  появившееся по ходу работы.                                                */
/* -------------------------------------------------------------------------- */

/* --- 1. Тихая плашка: по умолчанию ---------------------------------------- */
/*
 *  <Alert variant="WARNING">Срок действия ключа истекает</Alert>
 *
 *  Просто оформление: рамка, заливка, цвет. Замерено — в дереве доступности
 *  это generic без роли и без live-региона. Текст читается в обычном порядке
 *  чтения, как любой абзац.
 *
 *  Это верный выбор, когда плашка есть на странице с самого начала: делать
 *  её live-регионом значило бы заставлять скринридер зачитывать её вне
 *  очереди при каждой перерисовке.
 */

/* --- 2. live: сообщение, появившееся по ходу работы ----------------------- */
/*
 *  <Alert variant="ERROR" live>Не удалось сохранить</Alert>
 *
 *  Роль выводится из варианта, и это не косметика — от неё зависит, перебьёт
 *  ли сообщение то, что скринридер читает сейчас. Замерено в Chromium:
 *
 *      variant="ERROR"  → role="alert"   live=assertive, atomic
 *      остальные        → role="status"  live=polite,    atomic
 *
 *  assertive прерывает чтение немедленно, polite ждёт паузы. Поэтому live
 *  с ERROR — для того, что требует реакции прямо сейчас, а не для «сохранено».
 *
 *  Важное ограничение live-регионов: элемент должен существовать в DOM
 *  ДО того, как в нём появится текст. Плашка, смонтированная сразу с текстом,
 *  часто не объявляется вовсе. Поэтому держите контейнер постоянным,
 *  а меняйте содержимое:
 *
 *      <Alert live>{message}</Alert>          // объявится
 *      {message && <Alert live>{message}</Alert>}   // может промолчать
 *
 *  Своя роль перебивает выведенную: role передаётся обычным пропом.
 */

/* --- 3. Варианты ---------------------------------------------------------- */
/*
 *  ERROR | WARNING | SUCCESS, и без варианта — нейтральная.
 *
 *  Цвет варианта дублировать текстом не нужно, но и полагаться на него одного
 *  нельзя: цвет не единственный носитель смысла только тогда, когда сообщение
 *  само себя объясняет. «Ошибка» зелёной плашкой не станет понятнее.
 *
 *  Цвета перебиваются переменными плашки:
 *      <Alert style={{'--alert-accent': 'var(--purple-color-200)',
 *                     '--alert-tint':   'var(--purple-color-300)'}}>…</Alert>
 *
 *  --alert-accent идёт в заливку и рамку, --alert-tint — в иконку и акцентный
 *  текст: на разбавленной подложке сама заливка для текста слишком темна.
 */

/* --- Иконка --------------------------------------------------------------- */
/*
 *  Прямой <svg> внутри плашки и любой элемент с классом accent красятся
 *  тоном варианта автоматически. Декоративную иконку помечайте aria-hidden,
 *  иначе скринридер прочитает её имя перед текстом сообщения.
 */
/* -------------------------------------------------------------------------- */

import type {AlertProps} from "./Alert.interface.ts";
import styles from './Alert.module.css';

function Alert ({
                    variant,
                    live = false,
                    className = "",
                    ...props
                }: AlertProps) {
    const role = live ? (variant === 'ERROR' ? 'alert' : 'status') : undefined;

    return (
        <div data-variant={variant} className={className ? `${styles.alert} ${className}` : styles.alert} role={role}{...props}/>
    );
}

export {Alert};
