// Breadcrumbs.interface.ts
import type {ComponentPropsWithRef, MouseEvent, ReactNode} from 'react';

/** Одно звено пути. */
export interface Crumb {
    /** Подпись. Она же имя ссылки, поэтому писать её надо для человека. */
    label: ReactNode
    /**
     * Адрес. Есть — звено становится ссылкой, нет — обычным текстом:
     * уровень, у которого своей страницы не бывает («Настройки» над
     * разделами настроек), честнее показать неинтерактивным, чем
     * ссылкой в никуда.
     *
     * У последнего звена адрес не нужен и игнорируется — см. ниже.
     */
    href?: string
    /** Значок перед подписью. Сам по себе именем не считается. */
    icon?: ReactNode
    /** Своё имя для скринридера, если подпись сокращена до неузнаваемости. */
    'aria-label'?: string
}

interface BreadcrumbsOwnProps {
    /**
     * Путь целиком, от корня к текущей странице. Последнее звено —
     * то место, где человек находится сейчас.
     */
    items: Crumb[]
    /**
     * Когда сворачивать путь. По умолчанию решает ширина, а не длина
     * пути: на широком экране виден весь путь, каким бы длинным он
     * ни был.
     *
     * `'fit'` — по ширине самой коробки: ниже 40rem середина уезжает
     * под «…», ниже 22rem остаются только корень и текущая страница.
     * Решает `@container`, то есть движок, — ни замеров в JS,
     * ни перерисовок при изменении размера.
     *
     * Число — середина спрятана всегда, как только звеньев стало
     * больше этого числа. Сворачивание по ширине при этом остаётся:
     * на узком месте пропадёт и то, что число оставило.
     *
     * `false` — не сворачивать вовсе. Длинный путь на узком месте
     * тогда переносится на вторую строку.
     *
     *     <Breadcrumbs items={path}/>              // по ширине
     *     <Breadcrumbs items={path} collapse={4}/> // длиннее четырёх — под «…»
     *     <Breadcrumbs items={path} collapse={false}/>
     */
    collapse?: 'fit' | number | false
    /** Сколько звеньев оставлять в начале при сворачивании. По умолчанию одно. */
    head?: number
    /**
     * Сколько звеньев оставлять в конце при сворачивании, вместе
     * с текущим. По умолчанию два.
     */
    tail?: number
    /**
     * Разделитель между звеньями. По умолчанию «/».
     *
     * Это разметка, а не `content` в CSS: так разделитель попадает
     * в выделение и в копию, и скопированный путь остаётся путём.
     * От скринридера он спрятан — пауза между ссылками слышна и так.
     */
    separator?: ReactNode
    /**
     * Имя навигации для скринридера. По умолчанию «Хлебные крошки».
     * Если на странице две навигации подряд, имена обязаны различаться.
     */
    label?: string
    /** Подписи кнопки раскрытия. */
    labels?: Partial<BreadcrumbsLabels>
    /**
     * Щёлкнули по звену. Приходит до перехода, и `preventDefault()`
     * его отменяет — так роутер забирает навигацию себе, не теряя
     * настоящего адреса в разметке.
     */
    onNavigate?: (item: Crumb, index: number, event: MouseEvent<HTMLElement>) => void
}

export interface BreadcrumbsLabels {
    /** Имя кнопки «…», когда путь свёрнут. */
    expand: string
    /** Имя той же кнопки, когда путь раскрыт. */
    collapse: string
}

/**
 * Хлебные крошки: путь от корня к текущей странице.
 *
 *     <Breadcrumbs items={[
 *         {label: 'Главная', href: '/'},
 *         {label: 'Банк', href: '/bank'},
 *         {label: 'Счета', href: '/bank/accounts'},
 *         {label: 'Выписка'},
 *     ]}/>
 *
 * Это `<nav>` со списком `<ol>`: путь — ориентир, и скринридер обязан
 * находить его среди ориентиров; порядок звеньев значим, поэтому список
 * нумерованный. Последнее звено — не ссылка, а текст с `aria-current="page"`:
 * ссылка на страницу, где ты уже стоишь, обещает переход, которого нет
 * (рекомендация APG для breadcrumb).
 *
 * Когда сворачивать, решает проп `collapse`, и по умолчанию это ширина
 * самой коробки, а не длина пути: ниже 40rem середина уезжает под «…»,
 * ниже 22rem остаются только корень и текущая страница, а на широком
 * месте виден весь путь. Это делает `@container`, а не JS: ни замеров
 * ширины, ни наблюдателя, ни перерисовок при изменении размера.
 * Числом можно потребовать сворачивания независимо от ширины,
 * `false` — отключить его вовсе.
 *
 * Кнопка «…» раскрывает спрятанное на месте и сворачивает обратно
 * (`aria-expanded`). Поповера у неё нет намеренно: замерено в Chromium 141
 * на ширине 360px — раскрытый путь из семи звеньев занимает три строки
 * и сдвигает содержимое под собой на 56px, тогда как меню в поповере
 * пришлось бы класть поверх этого самого содержимого, да ещё и уводить
 * фокус. Сдвиг виден и обратим, перекрытие — нет.
 *
 * Переменные на коробке:
 *
 * | Переменная               | Что меняет                    |
 * |--------------------------|-------------------------------|
 * | `--breadcrumbs-gap`      | зазор вокруг разделителя      |
 * | `--breadcrumbs-size`     | высота цели нажатия           |
 * | `--breadcrumbs-color`    | цвет ссылок                   |
 * | `--breadcrumbs-current`  | цвет текущей страницы         |
 * | `--breadcrumbs-item-max` | потолок ширины звена; по умолчанию `none`, с ним длинная подпись обрезается многоточием |
 *
 * Ширина, ниже которой путь сворачивается, переменной не задаётся:
 * условие `@container` подстановку `var()` пока не принимает ни в одном
 * движке.
 *
 * Про ширину важное, как и у `Pagination`: коробка объявлена размерным
 * контейнером и берёт ширину у раскладки, а не у содержимого. В родителе,
 * который сам сжимается по содержимому (`width: fit-content`,
 * `justify-items: center` у блока), ширину придётся задать явно.
 */
export type BreadcrumbsProps = ComponentPropsWithRef<'nav'> & BreadcrumbsOwnProps;
