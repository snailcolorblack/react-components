import type {Meta, StoryObj} from '@storybook/react-vite';
import {Breadcrumbs} from './Breadcrumbs';
import type {Crumb} from './Breadcrumbs.interface.ts';

const ПУТЬ: Crumb[] = [
    {label: 'Главная', href: '/'},
    {label: 'Банк', href: '/bank'},
    {label: 'Переводы', href: '/bank/transfers'},
    {label: 'Счета', href: '/bank/accounts'},
    {label: 'KZ12 3456 7890 1234', href: '/bank/accounts/12'},
    {label: 'Выписки', href: '/bank/accounts/12/statements'},
    {label: 'Март 2026'},
];

const домик = (
    <svg viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.5">
        <path d="M2 7 8 2l6 5v7H2z" strokeLinejoin="round"/>
    </svg>
);

const meta = {
    title: 'Навигация/Breadcrumbs',
    component: Breadcrumbs,
    /*
     * Ширина задаётся единицами окна, а не процентами. Крошки —
     * размерный контейнер: своей ширины по содержимому у них нет,
     * а #storybook-root сжимается по содержимому (у body в index.css
     * стоит place-items: center). Проценты считались бы от той же
     * нулевой ширины, поэтому не спасают.
     */
    decorators: [
        Story => (
            <div style={{inlineSize: 'min(60rem, calc(100vw - 4rem))'}}>
                <Story/>
            </div>
        ),
    ],
    parameters: {
        layout: 'padded',
        docs: {
            description: {
                component: `Путь от корня к текущей странице: \`<nav>\` со списком \`<ol>\`, а не ряд ссылок.
Путь — ориентир, скринридер обязан находить его среди ориентиров, а порядок звеньев значим.

Последнее звено — не ссылка, а текст с \`aria-current="page"\`: ссылка на страницу, где
человек уже стоит, обещает переход, которого нет.

Разделитель — разметка, а не \`content\` в CSS. Замерено в Chromium 141: текст из \`::before\`
не копируется (путь вставлялся бы как «ГлавнаяБанкСчета») и попадает в имя ссылки —
у \`<a>\` с \`::before { content: "/ " }\` имя становится «/Банк».

Когда сворачивать, решает проп \`collapse\`, и по умолчанию это ширина самой коробки, а не
длина пути: ниже 40rem середина уезжает под «…», ниже 22rem остаются только корень и текущая
страница, а на широком месте путь виден целиком. Это делает \`@container\`, без замеров в JS
и перерисовок при изменении размера. Замерено: путь из семи звеньев просит 579px, держится
в одну строку до 580px и переносится на 575px — порог 40rem (640px) взят так, чтобы
сворачивание успевало раньше переноса; узкий порог срабатывает между 352px и 348px.

Числом (\`collapse={4}\`) можно потребовать сворачивания независимо от ширины, \`false\` —
отключить его вовсе.

Кнопка «…» раскрывает спрятанное на месте. Поповера у неё нет намеренно: на 320px раскрытый
путь из семи звеньев занимает три строки и сдвигает содержимое под собой на 56px, тогда как
меню легло бы поверх этого содержимого и увело фокус. Сдвиг виден и обратим вторым щелчком.

Контраст замерен по пикселям на фоне #121212: ссылки 7.08:1, разделители 6.91:1, текущая
страница 18.73:1.`,
            },
        },
    },
} satisfies Meta<typeof Breadcrumbs>;

export default meta;

type Story = StoryObj<typeof meta>;

/** Короткий путь: сворачивать нечего. */
export const Обычный: Story = {
    args: {items: ПУТЬ.slice(0, 3)},
};

/** Длинный путь, свёрнутый числом. Нажмите «…» — раскроется на месте. */
export const Длинный: Story = {
    args: {items: ПУТЬ, collapse: 4},
};

/** Сколько звеньев оставлять по краям — своё. */
export const СвоиКрая: Story = {
    args: {items: ПУТЬ, collapse: 4, head: 2, tail: 1},
};

/** По умолчанию: на широком месте виден весь путь, каким бы длинным он ни был. */
export const ПоШирине: Story = {
    args: {items: ПУТЬ},
};

/** Числом: середина под «…» всегда, сколько бы места ни было. */
export const ПоКоличеству: Story = {
    args: {items: ПУТЬ, collapse: 4},
};

/** Не сворачивать вовсе: на узком месте путь перенесётся на вторую строку. */
export const БезСворачивания: Story = {
    args: {items: ПУТЬ, collapse: false},
};

/** Свой разделитель. Он в разметке, поэтому копируется вместе с путём. */
export const СвойРазделитель: Story = {
    args: {items: ПУТЬ, separator: '›'},
};

/** Значок у корня. Именем ссылки он не становится — для этого есть подпись. */
export const СоЗначком: Story = {
    args: {
        items: [{...ПУТЬ[0], icon: домик}, ...ПУТЬ.slice(1)],
        collapse: 4 as const,
    },
};

/**
 * Звено без адреса — обычный текст: уровень, у которого своей страницы
 * не бывает, честнее показать неинтерактивным, чем ссылкой в никуда.
 */
export const БезАдреса: Story = {
    args: {
        items: [{label: 'Главная', href: '/'}, {label: 'Настройки'}, {label: 'Профиль'}],
    },
};

/**
 * Потолок ширины звена. По умолчанию его нет: обрезать подпись —
 * потеря смысла. Задан — текст обрезается многоточием, но в разметке
 * остаётся целым, и скринридер прочтёт его полностью.
 */
export const СПотолкомШирины: Story = {
    args: {
        items: ПУТЬ,
        collapse: false,
        style: {'--breadcrumbs-item-max': '10ch'} as React.CSSProperties,
    },
};

/** Узкое место: видны только корень и текущая страница. */
export const НаУзком: Story = {
    args: {items: ПУТЬ},
    decorators: [
        Story => (
            <div style={{inlineSize: 'min(20rem, 100%)'}}>
                <Story/>
            </div>
        ),
    ],
};
