// Button.interface.ts
import type {ComponentPropsWithRef} from 'react';

/**
 * Оформление. На поведение не влияет ни один из вариантов: роль, фокус,
 * клавиатура и форма одинаковы везде.
 *
 * `DEFAULT` — заливка акцентом. Главное действие экрана.
 * `OUTLINE` — рамка и подпись акцентом. Второстепенное действие.
 * `CONTRAST` — светлая заливка, тёмная подпись.
 * `INLINE` — как текст: ни заливки, ни рамки, ни отступов.
 *
 * `INLINE` предназначен для действия внутри предложения или сразу за ним —
 * «Отменить», «Показать ещё». Издалека он не читается как нажимаемый, его
 * единственный признак — цвет, поэтому главным действием экрана его делать
 * нельзя. И он высотой ровно в строку (замерено, 19px), то есть меньше
 * требуемых WCAG 2.2 24×24; критерий 2.5.8 делает исключение для целей
 * внутри текста, но на отдельный ряд кнопок оно не распространяется.
 */
export type ButtonVariant = 'INLINE' | 'OUTLINE' | 'CONTRAST' | 'DEFAULT';
export type ButtonSize = 'FULL' | 'FIT';

/**
 * Чем кнопка может отрисоваться.
 *
 * `button` — действие на этой же странице: отправить форму, открыть окно.
 * `a` — переход по адресу. Выглядит так же, но это ссылка, и ведёт себя
 * как ссылка: её можно открыть в новой вкладке, скопировать адрес,
 * а срабатывает она по Enter и не срабатывает по пробелу.
 *
 * `input type="button"` сюда не входит намеренно: у него нет детей вовсе —
 * React бросает исключение на любую вложенность, — подпись живёт только
 * в `value`, а псевдоэлементом её не дополнить (замерено: `::before`
 * на инпуте не создаёт бокса и не меняет его ширину). То есть ни иконки,
 * ни индикатора загрузки. Сверх `<button type="submit">` он не даёт ничего.
 */
export type ButtonTag = 'button' | 'a';

interface ButtonOwnProps<T extends ButtonTag> {
    /** Тег: кнопка или ссылка. По умолчанию кнопка. */
    as?: T
    variant?: ButtonVariant
    size?: ButtonSize
    active?: boolean
    /**
     * Действие уже идёт: клик гасится, появляется индикатор, подпись
     * остаётся на месте. Ставит `aria-busy` и `aria-disabled`, но не
     * `disabled` — иначе элемент выпал бы из табуляции вместе с фокусом.
     *
     * Ссылке это тоже подходит и означает «переход уже начался»:
     * повторные клики отбиваются, адрес остаётся на месте.
     *
     * Без него кнопка отправки берёт состояние у своей формы:
     *
     *     <form action={save}>
     *         <Button type="submit">Сохранить</Button>
     *     </form>
     *
     * Пока действие формы не доработало, кнопка сама показывает
     * индикатор и гасит повторные нажатия — ни состояния, ни пропа
     * писать не нужно.
     *
     * Три вещи про это стоит знать:
     *
     * 1. Читается ближайшая родительская форма, и только та, у которой
     *    есть `action`-функция. Обычная отправка на сервер сюда
     *    не попадает: страница всё равно перезагрузится.
     * 2. Загрузку показывают ВСЕ кнопки отправки этой формы — какая
     *    из них нажата, платформа не сообщает. `type="button"` рядом
     *    не затрагивается.
     * 3. Явный `loading` сильнее: `loading={false}` выключает связь
     *    с формой, `loading={pending}` подменяет её своим источником.
     */
    loading?: boolean
}

/**
 * Пропсы тега. Для ссылки два запрета, и оба не формальность.
 *
 * `disabled` у ссылки не существует. Выключить её нечем: убрать `href` —
 * значит потерять и фокус, и роль (замерено: AX-узел становится `generic`
 * с пустым именем, элемент выпадает из табуляции, и пользователь его просто
 * не найдёт). Ссылку не выключают, а убирают или заменяют текстом. Если
 * действие временно недоступно — это `<button disabled>`, а не ссылка.
 *
 * `type` у `<a>` означает MIME-подсказку, а не вид кнопки, и подставлять
 * туда `"button"` нельзя.
 *
 * Отдельно закрыт `popoverTarget`: по спецификации триггером поповера может
 * быть только кнопка, а в типах React 19 этот атрибут объявлен на общем
 * `HTMLAttributes`, то есть разрешён вообще везде. На ссылке он молча
 * ничего не делает — пусть лучше не компилируется.
 */
interface TagProps {
    button: ComponentPropsWithRef<'button'>
    a: Omit<ComponentPropsWithRef<'a'>, 'type'> & {
        disabled?: never
        type?: never
        popoverTarget?: never
        popoverTargetAction?: never
    }
}

/**
 * Кнопка или ссылка с одинаковым оформлением.
 *
 *     <Button>Сохранить</Button>
 *     <Button type="submit">Отправить</Button>
 *     <Button as="a" href="/pricing">Тарифы</Button>
 *
 * Пропсы наследуются от выбранного тега: `href`, `target` и `rel` появятся
 * только у `as="a"`, а `type`, `disabled`, `form`, `popoverTarget`
 * и `commandfor` — только у кнопки.
 */
export type ButtonProps<T extends ButtonTag = 'button'> =
    Omit<TagProps[T], 'as' | 'variant' | 'size' | 'active' | 'loading'>
    & ButtonOwnProps<T>;
