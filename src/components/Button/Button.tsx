// Button.tsx

/* -------------------------------------------------------------------------- */
/*  РАБОТА С КНОПКОЙ                                                          */
/*                                                                            */
/*  Кнопка или ссылка с общим оформлением: as="button" по умолчанию,          */
/*  as="a" — для перехода по адресу. type по умолчанию button, а не submit:    */
/*  кнопка внутри формы не должна отправлять её нечаянно — отправляющую        */
/*  помечайте явно, <Button type="submit">.                                    */
/* -------------------------------------------------------------------------- */

/* --- 1. Кнопка или ссылка -------------------------------------------------- */
/*
 *  <Button>Сохранить</Button>                        // действие
 *  <Button as="a" href="/pricing">Тарифы</Button>    // переход
 *
 *  Выглядят одинаково, ведут себя по-разному, и это не недоделка. Ссылку
 *  можно открыть в новой вкладке и скопировать адрес; срабатывает она
 *  по Enter и не срабатывает по пробелу — замерено в Chromium 141: кнопка
 *  отзывается на оба, ссылка только на Enter. Эмулировать пробел не нужно,
 *  скринридер объявляет её ссылкой, и пользователь ждёт именно такого
 *  поведения.
 *
 *  Правило выбора простое: меняется адрес — ссылка, меняется состояние —
 *  кнопка. Ссылка, которая никуда не ведёт, и кнопка, которая ведёт, ломают
 *  и клавиатуру, и «открыть в новой вкладке».
 *
 *  Пропсы приходят от выбранного тега: href, target и rel есть только
 *  у ссылки, а type, disabled, form, popoverTarget и commandfor —
 *  только у кнопки.
 */

/* --- 2. Почему нет input type="button" ------------------------------------- */
/*
 *  У него нет детей вовсе: React бросает исключение на любую вложенность,
 *  подпись живёт только в value. Дополнить её псевдоэлементом тоже нельзя —
 *  замерено, ::before на инпуте не создаёт бокса и не меняет ширину, тогда
 *  как у <button> та же строка раздувает его втрое. То есть ни иконки,
 *  ни индикатора загрузки. Сверх <button type="submit"> он не даёт ничего,
 *  поэтому его здесь и нет.
 */

/* --- 3. Варианты и размеры ------------------------------------------------ */
/*
 *  <Button>Сохранить</Button>                        // DEFAULT, заливка акцентом
 *  <Button variant="OUTLINE">Отмена</Button>         // только рамка и подпись
 *  <Button variant="CONTRAST">Далее</Button>         // светлая заливка
 *  <Button variant="INLINE">Показать ещё</Button>    // как текст, без коробки
 *
 *  <Button size="FULL">На всю ширину</Button>        // FIT по умолчанию
 *
 *  Осторожно с именами классов в CSS: size="FIT" использует класс .fill,
 *  а size="FULL" — класс .full. Названия почти совпадают и означают разное.
 */

/* --- 4. INLINE: кнопка как текст ------------------------------------------- */
/*
 *  <Typography>
 *      Черновик сохранён.{' '}
 *      <Button variant="INLINE" onClick={undo}>Отменить</Button>
 *  </Typography>
 *
 *  Ни заливки, ни рамки, ни отступов — только подпись акцентом, 7.70:1
 *  по фону страницы. В строку встаёт наравне с соседними словами: замерено,
 *  строка абзаца остаётся 19px, то есть кнопка её не распирает.
 *
 *  Это по-прежнему кнопка, а не текст: роль button, фокус, пробел и Enter,
 *  disabled и loading работают ровно так же. Меняется только оформление.
 *
 *  Куда ставить. INLINE — для действия внутри предложения или сразу после
 *  него: «Отменить», «Показать ещё», «Свернуть». Он намеренно не выглядит
 *  нажимаемым издалека, и единственный его признак — цвет, поэтому главное
 *  действие экрана им оформлять нельзя: пользователь его просто не найдёт.
 *
 *  Размер цели нажатия. Без отступов кнопка получается высотой в строку —
 *  замерено, 19px. WCAG 2.2 требует 24×24 (критерий 2.5.8), но делает
 *  исключение для целей внутри текста: в предложении INLINE ему
 *  соответствует. Рядом с другими INLINE в отдельном ряду — уже нет,
 *  и там либо нужны отступы, либо другой вариант.
 *
 *  Ссылке INLINE тоже идёт, и часто он там уместнее кнопки:
 *
 *      <Button as="a" href="/terms" variant="INLINE">условиями</Button>
 *
 *  Но подчёркивания у него нет — ссылка внутри текста без подчёркивания
 *  опознаётся только по цвету. Если такие ссылки будут встречаться в прозе
 *  часто, стоит добавить им text-decoration на уровне разметки вокруг.
 */

/* --- 5. Загрузка ---------------------------------------------------------- */
/*
 *  <Button loading>Сохранить</Button>
 *
 *  Внутри формы с action проп не нужен вовсе: кнопка отправки берёт
 *  pending у своей формы через useFormStatus и сама гасит повторные
 *  нажатия.
 *
 *  <form action={save}><Button type="submit">Сохранить</Button></form>
 *  <Button as="a" href="/report" loading>Отчёт</Button>
 *
 *  Клик гасится, но элемент НЕ получает disabled. Это намеренно: disabled
 *  выбрасывает его из порядка табуляции, и фокус в момент нажатия улетает
 *  в начало документа — пользователь клавиатуры теряет место. Вместо этого
 *  ставится aria-disabled, а обработчик отбивает клик сам. Замерено:
 *  role=button, disabled=true, busy=1, focusable=true — кнопка остаётся
 *  достижимой.
 *
 *  У ссылки это значит «переход уже начался»: повторные клики отбиваются
 *  тем же preventDefault, а адрес остаётся на месте. Enter на ссылке тоже
 *  поднимает click, так что гасится и он.
 *
 *  Подпись на время загрузки прячется через opacity, а не visibility или
 *  удалением из разметки: скрытый текст выпал бы из дерева доступности,
 *  и элемент остался бы без имени. Замерено — имя сохраняется. Заодно
 *  ширина не скачет.
 *
 *  Свои aria-disabled, aria-busy и data-state не затираются: loading
 *  и active только добавляют своё, но не убирают переданное. Раньше они стирались молча — атрибуты
 *  ставились после {...rest}, и <Button aria-disabled> без loading
 *  рендерился вовсе без атрибута.
 *
 *  Настоящий disabled тоже работает и означает другое: действие недоступно,
 *  а не выполняется. У ссылки его нет — и в типах он запрещён. Выключить
 *  ссылку нечем: убрать href значит потерять и фокус, и роль (замерено —
 *  AX-узел становится generic с пустым именем, элемент выпадает из
 *  табуляции). Недоступное действие — это <button disabled>, а не ссылка.
 */

/* --- 6. Активное состояние ------------------------------------------------ */
/*
 *  <Button active>Сегодня</Button>
 *
 *  Только оформление, заливка как у DEFAULT. Семантики «выбрано» здесь нет:
 *  если кнопка переключатель, добавьте aria-pressed, если вкладка —
 *  role="tab" с aria-selected, если это текущая страница в навигации —
 *  aria-current="page" на ссылке. Один лишь внешний вид скринридеру не виден.
 */

/* --- 7. Свои цвета -------------------------------------------------------- */
/*
 *  <Button style={{'--button-accent': 'var(--purple-color-100)',
 *                  '--button-accent-contrast': 'var(--contrast-color)'}}>…</Button>
 *
 *  Акцент задаётся парой: заливка и цвет подписи на ней. Порознь их менять
 *  нельзя — на ярком зелёном светлая подпись даёт 2.5:1. Ховер выводится
 *  сам: он подмешивает в заливку цвет её же подписи, поэтому тёмная заливка
 *  светлеет, а светлая темнеет.
 */

/* --- 8. Кнопка как триггер ------------------------------------------------ */
/*
 *  Открыть поповер или диалог можно разметкой, без состояния и обработчиков:
 *
 *      <Button popoverTarget="menu">Меню</Button>
 *      <Button commandfor="confirm" command="show-modal">Удалить</Button>
 *
 *  Только у as="button": это атрибуты кнопки, ссылка их не понимает.
 *  Подробности — в шапках Popover.tsx и Dialog.tsx.
 */
/* -------------------------------------------------------------------------- */

import {useFormStatus} from "react-dom";
import type {ElementType, MouseEvent} from "react";
import type {ButtonProps, ButtonSize, ButtonTag, ButtonVariant} from "./Button.interface.ts";
import styles from './Button.module.css'

const VARIANT_CLASS = {
    DEFAULT: styles.default,
    CONTRAST: styles.contrast,
    OUTLINE: styles.outline,
    INLINE: styles.inline
} satisfies Record<ButtonVariant, string>;
const SIZE_CLASS = {
    FIT: styles.fill,
    FULL: styles.full,
} satisfies Record<ButtonSize, string>;


function Button<T extends ButtonTag = 'button'>(props: ButtonProps<T>) {
    /*
     * Состояние ближайшей формы. Вне формы хук отдаёт pending: false,
     * поэтому вызывать его можно всегда — условных хуков не появляется.
     */
    const form = useFormStatus();

    const {
        as = 'button',
        className = "",
        size = 'FIT',
        variant = 'DEFAULT',
        active = false,
        loading,
        onClick,
        children,
        ...rest
            /* data-state объявлен здесь, потому что в типах React data-атрибуты
           разрешены в JSX, но индексировать по ним объект пропсов нельзя. */
    } = props as Omit<ButtonProps<'button'>, 'as'> & {as?: ButtonTag, 'data-state'?: string};

    const Component = as as ElementType;
    const classes = [styles.button, VARIANT_CLASS[variant], SIZE_CLASS[size], className].filter(Boolean).join(' ');
    const type = as === 'a' ? undefined : (rest.type ?? 'button');
    /*
     * Загрузка берётся из формы только у кнопки отправки: type="button"
     * рядом в той же форме делает что-то своё и крутиться не должна.
     * Явный loading (в том числе loading={false}) всегда главнее.
     */
    const busy = loading ?? (type === 'submit' && form.pending);


    return (
        <Component
            {...rest}
            type={type}
            aria-disabled={busy || rest['aria-disabled'] || undefined}
            aria-busy={busy || rest['aria-busy'] || undefined}
            data-state={active ? 'active' : rest['data-state']}
            className={classes}
            onClick={handleClick}
        >
            <span className={styles.label}>{children}</span>
            {busy && <span className={styles.spinner} aria-hidden="true"/>}
        </Component>
    );

    function handleClick(event: MouseEvent<HTMLElement>) {
        if (busy) {
            event.preventDefault();

            return;
        }
        onClick?.(event as MouseEvent<HTMLButtonElement>);
    }

}

export {Button};
