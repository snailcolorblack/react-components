// ButtonGroup.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/**
 * Вид группы.
 *
 * `LINE` — кнопки в строку, под активной линия, снизу граница. Лёгкий,
 * ничего не весит на странице, годится для разделов внутри блока.
 *
 * `PILL` — кнопки встык в коробке с фоном, под активной ездит таблетка.
 * Читается как единый переключатель, годится там, где выбор один
 * из нескольких равноправных.
 *
 * Оформление у обоих рисует один и тот же файл стилей, который берут
 * и вкладки: вид определён в одном месте.
 */
export type ButtonGroupVariant = 'LINE' | 'PILL';

interface ButtonGroupOwnProps {
    /**
     * Имя группы: «Способ оплаты», «Период».
     *
     * Обязательно. Группа — самостоятельный виджет, и без имени скринридер
     * прочитает варианты, но не скажет, к чему они относятся. Уходит
     * в `<legend>`, потому что внутри настоящий `<fieldset>`.
     */
    label: ReactNode
    /**
     * Показывать имя глазами. По умолчанию нет: обычно рядом уже есть
     * заголовок, а группе имя нужно для озвучки.
     *
     * Видимая подпись стоит НАД коробкой отдельной строкой, а не внутри
     * неё. Поэтому `fieldset` здесь без фона и отступов — фон у вложенной
     * оболочки: `legend` обязан быть первым ребёнком `fieldset`, и внутри
     * коробки он занял бы место между её краем и кнопками.
     */
    showLabel?: boolean
    /** Вид: линия или таблетка. По умолчанию таблетка. */
    variant?: ButtonGroupVariant
    /**
     * Имя поля в форме. Без него значение никуда не уходит, но группировка
     * всё равно работает: компонент подставляет своё имя, иначе варианты
     * не были бы одной группой и отмечались бы разом.
     */
    name?: string
    /** Выбранное значение. Управляемый режим. */
    value?: string
    /** Что выбрано поначалу. Неуправляемый режим. */
    defaultValue?: string
    /** Выбор изменился. */
    onChange?: (value: string) => void
}

/**
 * Группа кнопок с одним выбором: сегментированный переключатель.
 *
 *     <ButtonGroup label="Способ оплаты" name="pay" defaultValue="cash">
 *         <ButtonGroup.Item value="cash">В кассе</ButtonGroup.Item>
 *         <ButtonGroup.Item value="card">Картой</ButtonGroup.Item>
 *     </ButtonGroup>
 *
 * Внутри настоящие `<input type="radio">` с `appearance: none`, обёрнутые
 * в `<label>`. Отсюда всё бесплатно: стрелки ходят по вариантам, на всю
 * группу одна остановка табуляции, значение уходит в форму, а выбранное
 * состояние живёт в DOM — собственного React-состояния у компонента нет
 * вовсе, пока им не управляют снаружи.
 *
 * Длинный набор не переносится, а прокручивается, и вертикальное колесо
 * мыши полоса перехватывает: без этого до дальних кнопок с обычной мышью
 * не добраться — замерено, Chromium сам этого не делает, вместо полосы
 * уезжает страница. На краю прокрутка отдаётся странице, иначе колесо над
 * полосой переставало бы листать документ вовсе.
 *
 * Индикатор под активной кнопкой — линия у `LINE`, таблетка у `PILL` —
 * ездит на CSS anchor positioning: имя якоря есть только у выбранного
 * варианта, и переходы по `left`/`width` дают скольжение без единого
 * замера в JS. Там, где anchor positioning не поддержан, индикатора нет,
 * а его работу берёт сама активная кнопка.
 *
 * Это не вкладки. Если кнопки переключают панели с содержимым, нужен
 * `<Tabs>` — он берёт эту же оболочку и те же два вида, но объявляет себя
 * вкладками и связывает кнопки с панелями.
 */
export type ButtonGroupProps =
    Omit<ComponentPropsWithRef<'fieldset'>, 'onChange'>
    & ButtonGroupOwnProps;

interface ButtonGroupItemOwnProps {
    /** Значение варианта. Оно же уходит в форму. */
    value: string
    /** Содержимое кнопки: текст, значок, что угодно. */
    children: ReactNode
}

/**
 * Вариант внутри группы: `<label>` с настоящим `<input type="radio">`.
 *
 * Поле растянуто на всю кнопку, поэтому нажатие в любое её место — это
 * нажатие по полю. Остальные пропсы уходят на поле: `disabled`, `required`,
 * `ref`.
 */
export type ButtonGroupItemProps =
    Omit<ComponentPropsWithRef<'input'>, 'type' | 'value' | 'children' | 'name'>
    & ButtonGroupItemOwnProps;
