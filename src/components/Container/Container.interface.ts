// Container.interface.ts
import type {ElementType} from 'react';
import type {WrapperProps} from '../Wrapper/Wrapper.interface.ts';

/**
 * Насколько широко содержимое.
 *
 * `WIDE` — страница целиком: 1440px, предел для широких экранов.
 * `NORMAL` — обычный разворот: 1064px. Им набирается почти всё.
 * `PHONE` — смартфонный вид: 480px. Колонка остаётся узкой и на
 * большом экране — так читаются формы, вход и короткие экраны.
 *
 * Предел задаётся переменной `--container-max`, поэтому свой размер
 * делается без нового значения в этом списке.
 */
export type ContainerSize = 'WIDE' | 'NORMAL' | 'PHONE';

/**
 * Ограничитель ширины: держит содержимое по середине страницы и
 * не даёт строке растянуться на весь экран.
 *
 *     <Container>Содержимое</Container>
 *     <Container size="PHONE" as="main">Вход</Container>
 *
 * Отступ от края экрана — `clamp(1rem, 4vw, 2rem)`: 16px на смартфоне
 * и 32px на большом экране. Единица здесь `vw`, а не `cqi`, намеренно:
 * речь именно про поля до краёв ЭКРАНА, а не про ширину родителя.
 *
 * Отступ есть только у верхнего контейнера. Вложенный его не получает
 * вовсе — иначе колонки внутри страницы отъезжали бы от краёв дважды,
 * и чем глубже, тем сильнее.
 *
 * Полиморфен, как и `Wrapper`, на котором сделан: `as="main"`,
 * `as="section"`, `as="article"`. Фона и скругления у него нет —
 * это раскладка, а не поверхность.
 *
 * | Переменная            | Что меняет              |
 * |-----------------------|-------------------------|
 * | `--container-max`     | предел ширины           |
 * | `--container-padding` | отступ от краёв экрана  |
 *
 * Про родителя важное. Контейнер — размерный контейнер, и своё содержимое
 * он от внешнего мира прячет: в родителе, который сам сжимается по
 * содержимому (элемент flex-строки, `width: fit-content`), ему неоткуда
 * взять ширину, и он схлопывается в одни поля. Замерено в Chromium 141:
 * `#storybook-root` был элементом flex-строки и выходил 64px при окне
 * в 1200px — вместе с контейнером внутри. Оболочке страницы ширину
 * задают явно: в приложении это `#root` с `min-inline-size: 100vw`.
 */
export type ContainerProps<T extends ElementType = 'div'> =
    Omit<WrapperProps<T>, 'variant'>
    & {size?: ContainerSize};
