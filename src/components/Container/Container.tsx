/* -------------------------------------------------------------------------- */
/*  ОГРАНИЧИТЕЛЬ ШИРИНЫ                                                       */
/*                                                                            */
/*  Держит содержимое по середине страницы и не даёт строке растянуться       */
/*  на весь экран. Своего вида — фона, скругления — у него нет: это           */
/*  раскладка, и сделан он поверх Wrapper в варианте PLAIN.                   */
/* -------------------------------------------------------------------------- */

/* --- Отступ только у верхнего ---------------------------------------------- */
/*
 *  Поле до краёв экрана нужно один раз. Вложенный контейнер (колонка
 *  внутри страницы, карточка внутри колонки) отодвигал бы содержимое
 *  ещё раз, и чем глубже вложенность, тем сильнее: на трёх уровнях
 *  это уже 96px с каждой стороны на большом экране.
 *
 *  Поэтому отступ снимается у всякого контейнера внутри контейнера,
 *  а не только у прямого ребёнка: между ними почти всегда есть
 *  промежуточная разметка, и правило для прямого ребёнка её бы
 *  не пережило.
 */

/* --- Почему vw, а не cqi --------------------------------------------------- */
/*
 *  У Wrapper отступ считается в cqi — долях ширины родителя, и это
 *  правильно для блока содержимого. Здесь речь про другое: поля
 *  до краёв ЭКРАНА. Они обязаны быть одинаковыми у всех страниц
 *  приложения, независимо от того, во что контейнер вложен.
 */
/* -------------------------------------------------------------------------- */

import type {ElementType} from 'react';
import {Wrapper} from '../Wrapper/Wrapper.tsx';
import type {ContainerProps, ContainerSize} from './Container.interface.ts';
import styles from './Container.module.css';

const SIZE_CLASS = {
    WIDE: styles.wide,
    NORMAL: styles.normal,
    PHONE: styles.phone,
} satisfies Record<ContainerSize, string>;

function Container<T extends ElementType = 'div'>(props: ContainerProps<T>) {
    const {
        size = 'NORMAL',
        className = '',
        ...rest
    } = props as ContainerProps<'div'>;

    return (
        <Wrapper
            {...rest}
            variant="PLAIN"
            className={[styles.container, SIZE_CLASS[size], className].filter(Boolean).join(' ')}
        />
    );
}

export {Container};
