// Control.interface.ts

/**
 * Общая часть Radio и Checkbox. Компонента с таким именем нет: это то,
 * что у переключателей одинаково — оформление и способ показать состояние.
 * Поведение у них разное, поэтому и компонента два.
 */

import type {ReactNode} from 'react';

/**
 * Чем показано состояние «выбрано».
 *
 * `DEFAULT` — видимый кружок или квадрат рядом с подписью. Обычный случай:
 * список вариантов, согласие с условиями, настройка.
 *
 * `CHIP` — сам кружок скрыт, подсвечивается вся область целиком: фон
 * и рамка. Для плиток и тегов, где выбор — это карточка, а не строка
 * с галочкой. Подсветкой занимается контейнер, а не текст, поэтому
 * внутрь можно класть что угодно: картинку, несколько строк, цену.
 *
 * Одним цветом подписи состояние не показывается ни в одном из вариантов:
 * это нарушало бы WCAG 1.4.1 и полностью пропадало бы в режиме высокого
 * контраста, где цвета подменяет система.
 */
export type ControlVariant = 'DEFAULT' | 'CHIP';

export interface ControlOwnProps {
    /** Оформление: видимый индикатор или подсветка всей области. */
    variant?: ControlVariant
    /**
     * Подпись. Может быть разметкой — текст, картинка, несколько строк.
     *
     * Из неё собирается имя переключателя. Обойтись без неё можно, только
     * назвав его иначе — `aria-label` или `aria-labelledby`: безымянным
     * он остаться не может, это запрещено типом.
     *
     * Интерактива внутри быть не должно: обёртка это сам `<label>`,
     * и клик по вложенной ссылке или кнопке уйдёт переключателю.
     * Нужна ссылка рядом — выносите её за пределы компонента.
     */
    children?: ReactNode
    /**
     * Своя ошибка: то, чего браузер знать не может, — ответ сервера,
     * проверка по другим полям формы.
     *
     * Показывается под переключателем и объявляется его описанием. Пока
     * она задана, браузерное сообщение не показывается; снимается тоже
     * снаружи.
     *
     * Ошибки самого браузера (`required`) показывать не нужно: компонент
     * берёт их текст сам и кладёт туда же. Пузырь при этом гасится — он
     * исчезает по таймеру и на него нельзя сослаться.
     */
    error?: ReactNode
}

/**
 * Имя обязательно, но взять его можно откуда угодно: из подписи, из
 * `aria-label` или из `aria-labelledby`.
 *
 * Без этого условия безымянный переключатель проходил типы молча —
 * поле формально есть, просто никак не названо, и проверки такого не ловят.
 * Пустая подпись годится там, где имя стоит рядом: флажок в строке таблицы,
 * переключатель в шапке колонки.
 */
export type ControlNamed =
    | {children: ReactNode}
    | {children?: ReactNode, 'aria-label': string}
    | {children?: ReactNode, 'aria-labelledby': string};
