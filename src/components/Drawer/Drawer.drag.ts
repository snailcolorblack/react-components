/* -------------------------------------------------------------------------- */
/*  ПЕРЕТАСКИВАНИЕ                                                            */
/*                                                                            */
/*  Чистая арифметика жеста, без React и без DOM: куда панель уехала          */
/*  под пальцем и на какой ступени она окажется, когда палец отпустят.        */
/*  Отдельным файлом, потому что это единственное место, где есть что         */
/*  проверять числами.                                                        */
/* -------------------------------------------------------------------------- */

/** Насколько близко к краю надо дотянуть, чтобы панель закрылась. */
const CLOSE_PART = 0.4;
/** Скорость, после которой решает бросок, а не расстояние (px/мс). */
const FLICK = 0.5;

/** По какой оси едет панель. */
export type DragAxis = 'block' | 'inline';

/** Что известно о жесте к моменту отпускания. */
export interface DragRelease {
    /** Сколько пройдено в сторону закрытия, px. */
    distance: number;
    /** px/мс, со знаком: положительная — в сторону закрытия. */
    speed: number;
    /** Размер панели вдоль оси движения, px. */
    size: number;
    /** Текущая ступень. */
    step: number;
    /** Сколько всего ступеней. */
    steps: number;
}

/** Чем кончился жест: панель закрывается или встаёт на ступень. */
export type DragResult = {close: true} | {close: false, index: number};

/**
 * Сдвиг панели под пальцем.
 *
 * Положительный — в сторону закрытия. В обратную сторону панель
 * не едет вовсе: тянуть дальше открытого состояния некуда, и резина
 * там только путает. Исключение — когда есть ступень выше: тогда
 * обратный сдвиг разрешён, иначе ступени не достичь.
 */
function shift(distance: number, canGrow: boolean) {
    if (distance >= 0) return distance;

    return canGrow ? distance : 0;
}

/**
 * Что делать, когда палец отпустили.
 *
 * Решают две вещи: как далеко утащили от текущей ступени и как быстро.
 * Быстрый бросок закрывает даже с небольшого расстояния — это то,
 * чего человек и ждёт от жеста; медленное же перетаскивание меряется
 * долей размера панели.
 */
function settle({distance, speed, size, step, steps}: DragRelease): DragResult {
    const flick = Math.abs(speed) >= FLICK;
    /* «Прочь» — в сторону закрытия: вниз у нижней панели, вверх у верхней. */
    const away = flick ? speed > 0 : distance > 0;
    const far = Math.abs(distance) >= size * CLOSE_PART;

    if (!flick && !far) return {close: false, index: step};

    if (away) {
        /* С нижней ступени прочь — это закрытие. */
        if (step === 0) return {close: true};

        return {close: false, index: step - 1};
    }

    return {close: false, index: Math.min(step + 1, steps - 1)};
}

export {CLOSE_PART, FLICK, settle, shift};
