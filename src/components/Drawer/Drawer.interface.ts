// Drawer.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/** Откуда выезжает панель. */
export type DrawerSide = 'bottom' | 'top' | 'start' | 'end';

/**
 * Вид панели.
 *
 * `HANDLE` — с полосой-ручкой: за неё тянут пальцем, её же можно
 * нажать и подвигать стрелками с клавиатуры.
 * `PLAIN` — без ручки: панель закрывают своей кнопкой, Esc или
 * щелчком мимо.
 */
export type DrawerVariant = 'HANDLE' | 'PLAIN';

/**
 * Кому разрешено тянуть.
 *
 * `'touch'` (по умолчанию) — только пальцем: на мышь это поведение
 * никто не ожидает, и перетаскивание панели мышью чаще мешает.
 * `true` — всем, включая мышь и перо.
 * `false` — никому: панель двигается только пропами.
 */
export type DrawerDrag = 'touch' | boolean;

/**
 * Ступень раскрытия: сколько панель занимает.
 *
 * Любой размер CSS (`'40vh'`, `'20rem'`, `'50%'`), `'auto'` — по
 * содержимому, `'full'` — всё доступное место.
 */
export type DrawerSnap = string;

interface DrawerOwnProps {
    /** Открыта ли панель. Снаружи — открывается и закрывается этим. */
    open: boolean
    /**
     * Панель закрылась. Обязателен: закрыть её может не только ваша
     * кнопка, но и Esc, щелчок мимо и протаскивание вниз, а React
     * об этом иначе не узнает — состояние осталось бы `true`.
     */
    onClose: () => void
    /** Откуда выезжает. По умолчанию снизу. */
    side?: DrawerSide
    variant?: DrawerVariant
    /**
     * Ступени раскрытия по возрастанию. По умолчанию одна — `'auto'`,
     * то есть по содержимому, но не больше экрана.
     *
     *     snap={['40vh', 'full']}
     *
     * Потянули вверх — панель встала на следующую ступень, вниз —
     * на предыдущую, а с самой нижней ушла в закрытие.
     */
    snap?: DrawerSnap[]
    /** С какой ступени открывать. По умолчанию с первой. */
    defaultSnap?: number
    /** Ступень сменилась: перетаскиванием, клавишами или нажатием ручки. */
    onSnapChange?: (index: number, snap: DrawerSnap) => void
    drag?: DrawerDrag
    /** Имя панели для скринридера. Или свяжите заголовок через `aria-labelledby`. */
    label?: string
    /** Подписи ручки: их читает скринридер. */
    labels?: Partial<DrawerLabels>
    children?: ReactNode
}

export interface DrawerLabels {
    /** Имя ручки. */
    handle: string
    /** Подсказка о том, что делает нажатие. */
    hint: string
}

/**
 * Выезжающая панель: модальное окно, прижатое к краю экрана.
 *
 *     <Drawer open={open} onClose={close} label="Фильтры">
 *         <p>Содержимое</p>
 *     </Drawer>
 *
 *     <Drawer open={open} onClose={close} snap={['40vh', 'full']} label="Счета">
 *         <Scroll axis="block">…длинный список…</Scroll>
 *     </Drawer>
 *
 * Под панелью `<dialog>` с `showModal()`, поэтому ловушка фокуса,
 * Esc, возврат фокуса на триггер, слой поверх всего и затемнение
 * `::backdrop` приходят от браузера, а не пишутся здесь.
 *
 * Содержимое может быть любым — от двух полей до длинного списка:
 * своя прокрутка у панели включена, а перетаскивание пальцем
 * с неё начинается только тогда, когда список уже прокручен
 * к началу. Иначе жест спорил бы с прокруткой.
 *
 * Переменные на коробке:
 *
 * | Переменная          | Что меняет                          |
 * |---------------------|-------------------------------------|
 * | `--drawer-max`      | предел размера (по умолчанию 90dvh) |
 * | `--drawer-duration` | длительность выезда                 |
 * | `--drawer-radius`   | скругление у открытого края         |
 * | `--drawer-bg`       | фон                                 |
 */
export type DrawerProps =
    Omit<ComponentPropsWithRef<'dialog'>, 'open' | 'children'>
    & DrawerOwnProps;
