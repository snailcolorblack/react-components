// Field.focus.ts

/* -------------------------------------------------------------------------- */
/*  ПОВТОРНЫЙ КЛИК ПО КОРОБКЕ                                                 */
/*                                                                            */
/*  У Input и Textarea коробка — это <label>, и клик по ней ставит фокус      */
/*  в поле без обработчиков. Но только пока поле НЕ в фокусе.                 */
/*                                                                            */
/*  Если поле уже в фокусе, а нажали мимо него — по отступу коробки или       */
/*  по приписке, — браузер делает лишний круг. Замерено в Chromium 141,       */
/*  журнал событий на второй клик:                                            */
/*                                                                            */
/*      mousedown: label                                                      */
/*      focusout:  input      ← поле теряет фокус                             */
/*      mouseup:   label                                                      */
/*      click:     label                                                      */
/*      focusin:   input      ← активация label возвращает его назад          */
/*                                                                            */
/*  Между focusout и focusin поле действительно не в фокусе, и это видно:     */
/*  гаснет кольцо, плавающая подпись падает в центр и едет обратно наверх.    */
/*  На записи экрана это читается как мигание на каждый клик.                 */
/*                                                                            */
/*  Лечится отменой mousedown: без него фокус никуда не уходит, а активация   */
/*  label на click вызывает focus() у уже сфокусированного поля, то есть      */
/*  не делает ничего. Каретка при этом остаётся там, где стояла.              */
/*                                                                            */
/*  Отменяем ровно в одном случае — поле уже в фокусе и нажали не по нему.    */
/*  Первый клик остаётся полностью платформенным: он и фокус ставит,          */
/*  и каретку в нужное место, и выделение протягивает.                        */
/* -------------------------------------------------------------------------- */

import type {MouseEvent} from 'react';

/**
 * Удержать фокус в поле при повторном нажатии на коробку.
 *
 * @param event  нажатие на коробке поля
 * @param control класс самого поля внутри коробки (общий `Field.control`)
 */
function holdFocus(event: MouseEvent<HTMLElement>, control: string) {
    const node = event.currentTarget.querySelector(`.${control}`);

    /* Нажали по самому полю — пусть браузер ставит каретку как знает. */
    if (node === null || event.target === node) return;
    /* Поле ещё не в фокусе — первый клик трогать нельзя. */
    if (document.activeElement !== node) return;

    event.preventDefault();
}

export {holdFocus};
