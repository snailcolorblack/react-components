// Field.interface.ts
import type {ReactNode} from 'react';

/**
 * Общая часть контракта полей: Select, Input и Textarea.
 *
 * Сюда вынесено только то, что у них действительно одинаково. Всё
 * остальное — список у Select, аффиксы и маска у Input, авторост
 * у Textarea — живёт в их собственных интерфейсах.
 */
export interface FieldOwnProps {
    /**
     * Подпись поля. Она же плавающая метка: пока поле пустое, стоит
     * по центру вместо подсказки, а с появлением значения уезжает наверх
     * и уменьшается.
     *
     * Это именно подпись, а не placeholder: она остаётся на месте после
     * ввода, поэтому пользователь всегда видит, что это за поле, —
     * требование WCAG 3.3.2, которое обычный placeholder нарушает.
     *
     * Обязательна намеренно. Раньше была необязательной, и поле без неё
     * оставалось без имени — а у Select выходило хуже: `aria-labelledby`
     * продолжал ссылаться на пустую подпись, и именем кнопки становилось
     * одно значение («ничего не выбрано» у пустого multi). Проверки это
     * не ловят: имя формально есть, просто неверное.
     *
     * Подпись нужна и по виду: вся коробка построена вокруг плавающей
     * метки, без неё в поле остаётся пустая строка.
     */
    label: ReactNode
    /**
     * Имя поля в форме. Без него значение никуда не уходит — как
     * и у любого нативного поля.
     */
    name?: string
    /**
     * Своя ошибка: то, чего браузер знать не может, — ответ сервера,
     * проверка по другим полям формы.
     *
     * Показывается под полем и объявляется как описание поля. Пока она
     * задана, браузерное сообщение не показывается: снаружи знают больше.
     * Сбрасывается тоже снаружи — компонент чужую ошибку не снимает.
     *
     *     <Input label="Логин" error={taken ? 'Такой логин уже занят' : undefined}/>
     *
     * Ошибки самого браузера (`required`, `pattern`, `type`) показывать
     * не нужно: компонент берёт их текст сам, и в том же месте.
     */
    error?: ReactNode
}

/**
 * Переменные коробки. Объявлены на `.field` в общем модуле, поэтому
 * перебиваются на любом из трёх компонентов одинаково:
 *
 *     <Input label="Цена" style={{'--field-radius': '4px'}}/>
 *
 * | Переменная               | За что отвечает                          |
 * |-------------------------|------------------------------------------|
 * | `--field-bg`            | заливка коробки                          |
 * | `--field-fg`            | цвет содержимого                         |
 * | `--field-border`        | рамка в покое                            |
 * | `--field-border-active` | рамка активного поля                     |
 * | `--field-label`         | подпись в покое                          |
 * | `--field-label-active`  | подпись у активного поля                 |
 * | `--field-ring`          | кольцо фокуса                            |
 * | `--field-invalid`       | всё перечисленное у поля с ошибкой       |
 * | `--field-radius`        | скругление                               |
 * | `--field-padding-block` / `--field-padding-inline` | отступы       |
 * | `--field-line`          | высота строки значения                   |
 * | `--field-gap`           | зазор между подписью и значением         |
 * | `--field-label-size`    | размер подписи в уехавшем состоянии      |
 * | `--field-label-scale`   | во сколько раз она крупнее, стоя по центру |
 * | `--field-duration`      | длительность переходов                   |
 *
 * Повторное нажатие по коробке фокус не роняет. У Input и Textarea коробка —
 * это `<label>`, и браузер на нажатие мимо поля сперва снимает фокус, а потом
 * возвращает его активацией подписи: замерено, между `focusout` и `focusin`
 * поле действительно не в фокусе, и это видно миганием. Нажатие гасится
 * ровно в этом случае — поле уже в фокусе и нажали не по нему; первый клик
 * остаётся полностью платформенным.
 *
 * «Поле активно» и «поле в фокусе с клавиатуры» — разные вещи. Рамка
 * и подпись подсвечиваются по `:focus-within`, а кольцо появляется только
 * по `:focus-visible`. Иначе составное поле врёт: у Select фокус ходит между
 * кнопкой и пунктами списка, а кнопка по мышиному клику `:focus-visible`
 * не получает вовсе — замерено, после закрытия списка поле оставалось
 * в фокусе, но выглядело погасшим.
 *
 * Ошибку показывает `:user-invalid`, а не `:invalid`: второй красит пустое
 * обязательное поле сразу при открытии формы, ещё до того, как человек
 * к нему притронулся.
 *
 * Текст ошибки лежит под полем, в третьей строке сетки, и подключён к полю
 * через `aria-describedby` вместе с `aria-invalid`. Пузырь браузера при этом
 * гасится: он исчезает по таймеру, не попадает в дерево доступности и на него
 * нельзя сослаться. Текст берётся из `validationMessage`, а его язык — язык
 * браузера, а не страницы: замерено, в Chromium с английским интерфейсом
 * при `lang="ru"` выходит «Please fill out this field.». Где формулировка
 * важна, её задают пропом `error`.
 */
export type FieldVariables = never;
