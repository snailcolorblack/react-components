// Fieldset.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/** Как лежат элементы внутри группы. */
export type FieldsetOrientation = 'block' | 'inline';

interface FieldsetOwnProps {
    /**
     * Имя группы. Обязательно — в этом весь смысл компонента: без него
     * скринридер прочитает «переключатель, 1 из 3», но не скажет, что
     * выбирают тариф.
     *
     * Если имя не должно быть видно, не убирайте его, а спрячьте —
     * `hideLegend`. Замерено: скрытая легенда продолжает быть именем
     * группы в дереве доступности.
     */
    legend: ReactNode
    /**
     * Спрятать легенду визуально, оставив её именем группы. Прячется
     * обрезкой, а не `display: none`: скрытое таким образом выпало бы
     * из дерева доступности вместе с именем.
     */
    showLegend?: boolean
    /**
     * Направление: `block` — колонка (по умолчанию), `inline` — строка
     * с переносом. Легенда в раскладке не участвует и всегда остаётся
     * сверху, это поведение самого `<legend>`.
     */
    orientation?: FieldsetOrientation
}

/**
 * Группа полей — то, что даёт имя набору переключателей, флажков,
 * полей ввода или кнопок.
 *
 * Это обычный `<fieldset>` с `<legend>` первым ребёнком (порядок гарантирован
 * конструкцией: `legend` приходит пропсом, а не из `children`, и вставить
 * что-то перед ним нельзя — иначе элемент перестал бы быть легендой).
 *
 * Отсюда два свойства платформы, которых нет у самодельной обёртки с
 * `role="group"`:
 *
 * `disabled` гасит всё внутри разом — вложенные поля начинают матчить
 * `:disabled` и перестают брать фокус. Их собственное свойство `disabled`
 * при этом остаётся `false`: выключает не атрибут, а предок, и проверять
 * надо селектором, а не полем.
 *
 * Элемент внутри самой легенды под это не попадает: он остаётся доступным,
 * когда всё остальное погашено. На этом держится «выключатель раздела» —
 * флажок в легенде, которым группа включается обратно.
 *
 * Для радиогруппы можно добавить `role="radiogroup"` — он принимается
 * и не ломает роли вложенных переключателей. Без него роль будет `group`,
 * что для радио тоже допустимо.
 */
export type FieldsetProps = ComponentPropsWithRef<'fieldset'> & FieldsetOwnProps;
