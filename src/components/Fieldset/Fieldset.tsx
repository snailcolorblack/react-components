// Fieldset.tsx

/* -------------------------------------------------------------------------- */
/*  РАБОТА С ГРУППОЙ ПОЛЕЙ                                                    */
/*                                                                            */
/*  Обычный <fieldset> с <legend> первым ребёнком. Легенда приходит пропсом,   */
/*  а не из children, и это не украшение API: легендой считается только        */
/*  первый ребёнок fieldset, и стоит кому-то вставить перед ней <div>, как     */
/*  группа молча теряет имя. Пропсом такой порядок гарантирован.               */
/* -------------------------------------------------------------------------- */

/* --- 1. Зачем группа вообще -------------------------------------------------*/
/*
 *  <Fieldset legend="Тариф">
 *      <Radio name="plan" value="free">Бесплатный</Radio>
 *      <Radio name="plan" value="pro">Профессиональный</Radio>
 *  </Fieldset>
 *
 *  Без неё скринридер прочитает «Бесплатный, переключатель, 1 из 2»,
 *  но не скажет, что именно выбирают. Имя набору даёт легенда.
 *
 *  Заворачивать можно не только переключатели: флажки, поля ввода, кнопки —
 *  всё, что образует один смысловой блок.
 */

/* --- 2. Имя есть всегда ---------------------------------------------------- */
/*
 *  <Fieldset legend="Способ оплаты" hideLegend orientation="inline">…</Fieldset>
 *
 *  legend обязателен. Если показывать его не нужно, он прячется, а не
 *  убирается: обрезкой, а не display: none. Замерено — скрытая таким
 *  образом легенда не занимает места и остаётся именем группы,
 *  AX-узел показывает role=group и то же имя.
 */

/* --- 3. Выключение всей группы --------------------------------------------- */
/*
 *  <Fieldset legend="Доставка" disabled>…</Fieldset>
 *
 *  Гасит все поля внутри разом — это платформа, не наш код. Две тонкости,
 *  обе замерены:
 *
 *  Собственное свойство поля остаётся прежним: input.disabled === false,
 *  хотя input.matches(':disabled') === true и фокус оно не берёт.
 *  Выключает предок, а не атрибут, поэтому проверять надо селектором.
 *
 *  Элемент внутри самой легенды под выключение НЕ попадает и фокус берёт.
 *  На этом держится «выключатель раздела»:
 *
 *      <Fieldset disabled={!enabled} legend={
 *          <Checkbox checked={enabled} onChange={…}>Своя доставка</Checkbox>
 *      }>…</Fieldset>
 *
 *  Флажок в легенде останется живым и включит группу обратно.
 */

/* --- 4. Роль --------------------------------------------------------------- */
/*
 *  <Fieldset legend="Тариф" role="radiogroup">…</Fieldset>
 *
 *  Без role fieldset даёт group — для радио этого достаточно, так написано
 *  и в APG. role="radiogroup" тоже принимается и роли вложенных
 *  переключателей не ломает: замерено, внутри остаются radio.
 */

/* --- 5. Раскладка ---------------------------------------------------------- */
/*
 *  orientation="block"   колонка, по умолчанию
 *  orientation="inline"  строка с переносом
 *
 *  Легенда в раскладке не участвует: браузер выносит её из потока и кладёт
 *  сверху при любом display у fieldset. Поэтому отступ под ней задан
 *  отдельным margin, а не общим gap — gap до неё не дотягивается.
 */

/* --- 6. Перерисовки -------------------------------------------------------- */
/*
 *  Состояния, хуков и эффектов нет: компонент считает строку классов
 *  и отдаёт разметку.
 */
/* -------------------------------------------------------------------------- */

import type {FieldsetOrientation, FieldsetProps} from './Fieldset.interface.ts';
import styles from './Fieldset.module.css';

const ORIENTATION_CLASS = {
    block: styles.block,
    inline: styles.inline,
} satisfies Record<FieldsetOrientation, string>;

function Fieldset({
                      legend,
                      showLegend = false,
                      orientation = 'block',
                      className = '',
                      children,
                      ...props
                  }: FieldsetProps) {

    const classes = [styles.fieldset, ORIENTATION_CLASS[orientation], className]
        .filter(Boolean)
        .join(' ');

    return (
        <fieldset {...props} className={classes}>
            <legend className={showLegend ? styles.legend : styles.hiddenLegend}>
                {legend}
            </legend>
            {children}
        </fieldset>
    );
}

export {Fieldset};
