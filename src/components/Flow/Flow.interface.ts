// Flow.interface.ts
import type {ComponentType, Dispatch, ReactNode, SetStateAction} from 'react';

/**
 * Шаг процесса.
 *
 * Имя — не подпись, а ключ: оно уезжает в адрес (`?step=quality`),
 * по нему шаг ищут при возврате и им же помечен черновик. Менять его
 * у живого процесса нельзя: ссылки и черновики перестанут открываться.
 */
export interface FlowStep<T = object> {
    /** Ключ шага. Он же в адресе. */
    name: string;
    /** Что рисовать. Компонент читает состояние через `useFlow()`. */
    component: ComponentType;
    /**
     * Итоговый экран: «готово» или «не вышло». Такой шаг не участвует
     * ни в порядке, ни в счётчике «шаг 2 из 5» — его там быть не должно,
     * это не часть пути, а его конец.
     *
     * Попасть на него можно только через `finish(ok, reason)`; сам
     * процесс приводит сюда после удачного `onFinish`. Что показать,
     * решает сам экран по `status`.
     *
     *     {name: 'result', component: Result, result: true}
     */
    result?: boolean;
    /**
     * Показывать ли шаг. Вернул `false` — шаг выпадает и из порядка,
     * и из счётчика «шаг 2 из 5», как будто его и не объявляли.
     *
     *     {name: 'comment', component: Comment, when: data => !data.resolved}
     */
    when?: (data: T) => boolean;
    /**
     * Что сделать перед уходом вперёд. Здесь живёт всё, чего во Flow нет
     * намеренно: проверка значений любой библиотекой и отправка шага
     * на сервер.
     *
     * Может быть асинхронным — пока он идёт, `pending` равен `true`.
     * На последнем шаге отрабатывает перед `onFinish`, а не вместо него:
     * `onLeave` сохраняет свой шаг, `onFinish` завершает весь процесс.
     *
     * Вернул `false` — перехода не будет, и это не ошибка: так
     * сообщают «проверка не прошла», а что показать, решает сам шаг.
     * Бросил исключение — перехода тоже не будет, но оно попадёт
     * в `error`: так отличается упавший запрос от непройденной проверки.
     *
     *     onLeave: async data => {
     *         const parsed = schema.safeParse(data);
     *         if (!parsed.success) { setErrors(parsed.error); return false; }
     *         await api.save(parsed.data);
     *     }
     */
    onLeave?: (data: T, flow: FlowTools<T>) => unknown;
}

/** Чем шаг распоряжается изнутри `onLeave` и `onFinish`. */
export interface FlowTools<T = object> {
    /**
     * Закончить процесс и показать итоговый экран.
     *
     * Так разводятся две разные неудачи: поправимая (неверное значение,
     * сорвавшаяся сеть) — это `false` или исключение, после них человек
     * остаётся на шаге и пробует снова; и окончательная (заявка
     * просрочена, ссылка уже использована) — это `finish(false, reason)`,
     * после неё возвращаться некуда.
     */
    finish: (ok: boolean, reason?: unknown) => void;
    /** Поменять данные, не выходя из колбэка. */
    setData: Dispatch<SetStateAction<T>>;
}

/** Чем кончился процесс. */
export interface FlowResult {
    /** Удачно ли. */
    ok: boolean;
    /** Почему не вышло: то, что передали в `finish`. */
    reason?: unknown;
}

/** Что отдаёт `useFlow()` внутри процесса. */
export interface FlowState<T = object> {
    /** Текущий шаг целиком. */
    step: FlowStep<T>;
    /** Номер текущего шага среди видимых, от нуля. */
    currentStepIndex: number;
    /** Сколько шагов видно при нынешних данных. */
    stepsLength: number;
    /** Данные процесса. Общие на все шаги. */
    data: T;
    /** Поменять данные. Как `useState`: значением или функцией. */
    setData: Dispatch<SetStateAction<T>>;
    /**
     * Вперёд. Сначала отрабатывает `onLeave` текущего шага; если он
     * вернул `false` или бросил исключение, перехода не будет.
     * С последнего видимого шага вызывает `onFinish`.
     *
     * Возвращает, состоялся ли переход.
     */
    goNextStep: () => Promise<boolean>;
    /** Назад. Без проверок: назад всегда можно. */
    goPrevStep: () => void;
    /** К шагу по имени. Только к пройденному или к текущему. */
    goToStep: (name: string) => void;
    /** Идёт `onLeave` или `onFinish`. */
    pending: boolean;
    /** Что бросил `onLeave` или `onFinish`. Сбрасывается на переходе. */
    error: unknown;
    /** Первый видимый шаг. */
    isFirst: boolean;
    /** Последний видимый шаг. */
    isLast: boolean;
    /**
     * Чем кончился процесс. Пока он идёт — `undefined`; на итоговом
     * экране — `{ok, reason}`. По нему экран и решает, показать
     * «готово» или «не вышло».
     */
    status: FlowResult | undefined;
    /** Закончить процесс и уйти на итоговый экран. */
    finish: (ok: boolean, reason?: unknown) => void;
    /** Забыть черновик. Сам он чистится после удачного `onFinish`. */
    clearDraft: () => void;
}

export interface FlowProps<T = object> {
    /** Шаги по порядку. */
    steps: FlowStep<T>[];
    /** Данные, с которых процесс начинается. */
    initial: T;
    /**
     * Ключ черновика. Передан — процесс переживает перезагрузку
     * страницы: данные, текущий шаг и пройденный путь сохраняются
     * при каждом переходе и чистятся после удачного завершения.
     * Не передан — черновика нет вовсе.
     *
     * Класть сюда персональное не стоит: хранилище браузера доступно
     * любому скрипту на домене и переживает закрытие вкладки.
     */
    draft?: string;
    /**
     * Имя параметра в адресе. По умолчанию `step`.
     *
     * Процесс живёт в адресе, а не только в памяти: кнопки «назад»
     * и «вперёд» у браузера работают сами, ссылку можно скопировать,
     * а перезагрузка не выбрасывает в начало.
     */
    param?: string;
    /**
     * Завершение: вызывается на уходе с последнего видимого шага.
     * Прошло без исключения — процесс сам уходит на итоговый экран
     * с `ok: true`, если такой шаг объявлен.
     */
    onFinish?: (data: T, flow: FlowTools<T>) => unknown;
    /** Шаг сменился. Удобно для аналитики. */
    onStepChange?: (name: string, data: T) => void;
    /**
     * Общая рамка шагов: ход дела, заголовок, кнопки — всё, что у шагов
     * одинаково. Flow заворачивает в неё каждый шаг, и писать её в каждом
     * больше не нужно.
     *
     *     function Frame({children}: {children: ReactNode}) {
     *         const {goNextStep, isLast} = useFlow();
     *         return <div>{children}<Button onClick={goNextStep}>…</Button></div>;
     *     }
     *
     *     <Flow steps={STEPS} initial={EMPTY} layout={Frame}/>
     *
     * Итоговый экран в рамку не заворачивается: процесс кончился, и ни
     * счётчика, ни «дальше» там быть не должно. Если рамка нужна и ему,
     * он нарисует её сам — он такой же обычный компонент.
     */
    layout?: ComponentType<{children: ReactNode}>;
    /** Что показать, пока процесс не готов (восстанавливается черновик). */
    fallback?: ReactNode;
}
