// Input.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';
import type {FieldOwnProps} from '../Field/Field.interface.ts';

interface InputOwnProps extends FieldOwnProps {
    /**
     * Показанное значение. Управляемый режим: значение приходит снаружи,
     * и снаружи же меняется в `onChange`.
     *
     * Можно передавать как уже размеченное маской, так и «сырое»: перед
     * показом значение всё равно проходит через маску, а она идемпотентна.
     * `'9161234567'` и `'+7 916 12-34-56'` при одной и той же маске дадут
     * одно и то же поле.
     */
    value?: string | number
    /** Начальное значение для неуправляемого режима. */
    defaultValue?: string | number
    /**
     * Значение изменилось.
     *
     * Первым приходит то, что видно в поле (и что уйдёт в форму), вторым —
     * только содержательные символы, без литералов маски и без аффиксов:
     *
     *     onChange={(view, raw) => {…}}   // '+7 916 12-34-56', '9161234'
     */
    onChange?: (value: string, raw: string) => void
    /**
     * Маска: `#` — место под символ, всё остальное литералы. Литералы
     * подставляются сами, в `raw` не попадают и при вводе игнорируются.
     *
     *     <Input label="Телефон" mask="+7 ### ##-##-##" format={/\d/}/>
     *
     * Сама по себе маска НЕ ограничивает, что можно набрать в слоте:
     * она отвечает за раскладку. Чтобы в телефон нельзя было ввести
     * буквы, добавьте `format`.
     *
     * Длина ограничена числом слотов: лишнее не вводится и не вставляется.
     * Поэтому вместе с маской нельзя задать `maxLength`, `minLength`
     * и `pattern` — тип их запрещает. Они считают показанное значение,
     * то есть вместе с литералами: `maxLength={10}` обрезал бы строку
     * посреди разделителя, а `pattern="\d{9}"` не совпал бы никогда.
     * Если нужна проверка сверх маски — `format` или проп `error`.
     */
    mask?: string
    /**
     * Какие символы допустимы. Проверяется посимвольно, всё прочее
     * не попадает в поле — ни с клавиатуры, ни вставкой.
     *
     *     format={/\d/}          // только цифры
     *     format={/[a-z\-]/i}    // латиница и дефис
     *
     * Флаги `g` и `y` снимаются: они переносят `lastIndex` между вызовами
     * и делали бы проверку одного и того же символа непредсказуемой.
     */
    format?: RegExp
    /**
     * Приписка слева от введённого: «https://», «+7», «₽».
     *
     * Поле с префиксом всегда держит подпись наверху, даже пустое: иначе
     * съехавшая в центр подпись легла бы прямо на приписку.
     *
     * По умолчанию это только отображение — в значение и в форму она
     * не попадает, стереть её нельзя, каретка её не видит. Для скринридера
     * приписка уходит в `aria-describedby`, то есть читается после имени
     * поля, а не как часть значения.
     */
    prefix?: ReactNode
    /** Приписка справа. Работает так же, как `prefix`. */
    suffix?: ReactNode
    /**
     * Включить приписки в значение. Тогда `onChange` отдаёт их вместе
     * с введённым, а в форму уходит скрытое поле с полной строкой —
     * само поле ввода остаётся без `name`, чтобы значение не отправилось
     * дважды.
     *
     * Приписки при этом всё равно не редактируются: они не часть текста
     * в поле, а его обрамление.
     *
     * Внимание: проверку проходит набранное, а отправляется полное. Для
     * `type="url"` с префиксом `https://` это расходится — браузер забракует
     * `example.com` как не-URL, хотя ушла бы верная строка. С припиской
     * в значении держите `type="text"`, а форму проверяйте на своей стороне
     * или пропом `error`.
     */
    affixInValue?: boolean
    /**
     * Подсказка внутри поля. Видна только у поля в фокусе: в покое её
     * место занимает подпись, и два текста наложились бы друг на друга.
     *
     * Подсказка дополняет подпись, но не заменяет её: она исчезает при
     * первом же символе.
     */
    placeholder?: string
}

/**
 * Текстовое поле.
 *
 *     <Input label="Имя" name="name"/>
 *
 *     <Input label="Телефон" name="phone" mask="+7 ### ##-##-##" format={/\d/}/>
 *
 *     <Input label="Цена" suffix="₽" format={/\d/} inputMode="numeric"/>
 *
 * Внутри настоящий `<input>`: типы, `required`, `minLength`, `pattern`,
 * автозаполнение, проверка формы и объявление ошибки — всё платформенное.
 * Компонент добавляет коробку с плавающей подписью (общую с Select
 * и Textarea), маску и приписки.
 *
 * Обёртка — `<label>`, поэтому клик по любому месту коробки ставит фокус
 * в поле: это делает браузер, обработчиков нет.
 *
 * Ошибка показывается после того, как человек закончил ввод (уход фокуса
 * или попытка отправить форму), а не при открытии формы. Текст — тот же,
 * что браузер показал бы в пузыре, но лежит под полем, в разметке, и связан
 * с полем через `aria-describedby`. Своя ошибка — проп `error`.
 *
 * Остальные пропсы уходят на `<input>`: `type`, `required`, `disabled`,
 * `inputMode`, `autoComplete`, `ref`.
 */
/** Нативная часть: всё, что уходит прямо на `<input>`. */
type Native = Omit<ComponentPropsWithRef<'input'>, 'onChange' | 'value' | 'defaultValue' | 'prefix' | 'size'>;

/**
 * Ограничения, которые считают ПОКАЗАННОЕ значение, вместе с литералами
 * маски. С маской они врут, поэтому в размеченном поле их нет.
 */
type Counted = 'maxLength' | 'minLength' | 'pattern';

export type InputProps =
    | (InputOwnProps & {mask: string} & Omit<Native, Counted>)
    | (InputOwnProps & {mask?: undefined} & Native);
