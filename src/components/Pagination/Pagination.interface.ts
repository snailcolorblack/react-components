// Pagination.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

interface PaginationOwnProps {
    /** Текущая страница. Считается от единицы, как её видит человек. */
    page: number
    /** Сколько всего страниц. Меньше двух — компонент не рисуется вовсе. */
    total: number
    /**
     * Куда ведёт номер страницы. Есть этот проп — номера становятся
     * ссылками `<a href>`, нет — кнопками.
     *
     * Ссылка лучше везде, где страница и правда отдельный адрес: её можно
     * открыть в соседней вкладке, скопировать, она видна поисковику
     * и работает без JS. Кнопки нужны там, где адрес не меняется —
     * таблица внутри диалога или вкладки.
     *
     *     href={page => `/товары?страница=${page}`}
     */
    href?: (page: number) => string
    /**
     * Выбрали страницу. Приходит и от номеров, и от стрелок.
     *
     * В режиме ссылок тоже вызывается — перед переходом, и если вызвать
     * `event.preventDefault()`, перехода не будет: так роутер забирает
     * навигацию себе, не теряя настоящего адреса в разметке.
     */
    onChange?: (page: number, event: React.MouseEvent<HTMLElement>) => void
    /**
     * Сколько номеров показывать по сторонам от текущего. По умолчанию
     * два. На узком месте становится на один меньше — само, через
     * container queries, без замеров в JS.
     */
    siblings?: number
    /** Сколько номеров всегда показывать по краям. По умолчанию один. */
    boundaries?: number
    /** Стрелки «назад» и «вперёд». По умолчанию есть. */
    arrows?: boolean
    /** Двойные стрелки «в начало» и «в конец». По умолчанию есть. */
    edges?: boolean
    /**
     * Надпись «Страница 3 из 20» рядом с номерами. По умолчанию есть
     * и на узком месте остаётся единственным, что видно глазами, когда
     * номера не влезают.
     *
     * Своя: `status={(page, total) => `${page} / ${total}`}`.
     */
    status?: boolean | ((page: number, total: number) => ReactNode)
    /**
     * Имя всей навигации для скринридера. По умолчанию «Постраничная
     * навигация». Если пагинаций на странице две (сверху и снизу
     * таблицы), имена обязаны различаться — иначе в списке ориентиров
     * они неотличимы.
     */
    label?: string
    /**
     * Подписи кнопок. Меняются целиком, чтобы не вшивать русский
     * в компонент намертво.
     */
    labels?: Partial<PaginationLabels>
}

export interface PaginationLabels {
    /** Имя номера страницы. Внутри обязан быть сам номер (WCAG 2.5.3). */
    page: (page: number) => string
    first: string
    previous: string
    next: string
    last: string
    status: (page: number, total: number) => string
}

/**
 * Постраничная навигация: номера страниц, стрелки и надпись «3 из 20».
 *
 *     <Pagination page={page} total={20} onChange={setPage}/>
 *     <Pagination page={page} total={20} href={p => `/товары?страница=${p}`}/>
 *
 * Это `<nav>` со списком, а не ряд кнопок: постраничная навигация —
 * ориентир, и скринридер обязан находить её в списке ориентиров. Текущая
 * страница помечена `aria-current="page"` — это и есть «вы здесь»,
 * отдельного aria-состояния для неё не существует.
 *
 * Сами кнопки и ссылки — общий `Button`: оформление, кольцо фокуса,
 * выключенное состояние и поведение в высоком контрасте у пагинации
 * не свои.
 *
 * Переменные на коробке:
 *
 * | Переменная           | Что меняет               |
 * |----------------------|--------------------------|
 * | `--pagination-gap`   | зазор между кнопками     |
 * | `--pagination-size`  | сторона кнопки с номером |
 *
 * Ширина, ниже которой номеров становится меньше, переменной не задаётся:
 * условие `@container` подстановку `var()` пока не принимает ни в одном
 * движке. Она зашита в стилях и меняется только там.
 *
 * Важное про ширину: пагинация — размерный контейнер, и свою ширину она
 * берёт у раскладки, а не у содержимого. В обычном месте (блок, элемент
 * flex-строки, клетка сетки) это незаметно — она занимает всю доступную
 * ширину. Но родитель, который сам сжимается по содержимому
 * (`width: fit-content`, `justify-items: center` у блока, элемент
 * flex-строки без растяжения), получит от неё ноль, и кнопки встанут
 * столбиком. Там ширину нужно задать явно — родителю или самой пагинации.
 */
export type PaginationProps =
    Omit<ComponentPropsWithRef<'nav'>, 'onChange'>
    & PaginationOwnProps;
