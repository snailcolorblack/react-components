// Popover.interfave.ts
import type {ComponentPropsWithRef} from 'react';

/**
 * С какой стороны триггера раскрывается поповер. Значения логические:
 * в RTL inline-end сам уезжает налево.
 *
 * Это только предпочтение. Если с этой стороны не хватает места, браузер
 * перевернёт поповер сам — за это отвечает position-try-fallbacks в стилях.
 */
export type PopoverPlacement = 'block-end' | 'block-start' | 'inline-end' | 'inline-start';

interface PopoverOwnProps {
    /**
     * Обязателен: по нему триггер находит поповер через popovertarget,
     * и из него же выводится имя якоря для привязки к триггеру.
     */
    id: string
    /**
     * `auto` — закрывается по Esc и клику мимо, и одновременно открыт может
     * быть только один. `manual` — закрывается только программно, живёт
     * рядом с другими. `hint` — для подсказок, закрывается при открытии
     * любого `auto`.
     */
    popover?: 'auto' | 'manual' | 'hint'
    /**
     * Имя поповера для скринридера. Без него `<div popover>` попадает
     * в дерево доступности как безымянная группа: роль есть, названия нет.
     *
     * Если заголовок уже есть в разметке, лучше связать с ним через
     * aria-labelledby, чем дублировать текст здесь.
     */
    label?: string
    /** С какой стороны триггера раскрываться. По умолчанию снизу. */
    placement?: PopoverPlacement
    /**
     * Имя якоря, если привязываться нужно не к триггеру, а к другому
     * элементу — тот должен объявить его через CSS anchor-name.
     *
     * По умолчанию не нужен: элемент, открывший поповер через popovertarget
     * или commandfor, браузер делает его якорем автоматически.
     */
    anchor?: `--${string}`
}

/**
 * Поповер — всплывающее окно без затемнения: не забирает фокус, не запирает
 * его внутри и не блокирует страницу. Этим он отличается от Dialog.
 *
 * Открывается разметкой, без состояния и без обработчиков:
 *
 *   <Button popoverTarget="user-menu">Меню</Button>
 *   <Popover id="user-menu" label="Меню">…</Popover>
 *
 * Кнопка, открывшая поповер, становится его якорем автоматически, поэтому
 * привязывать их друг к другу вручную не нужно.
 *
 * Роль по умолчанию — `group`. Под содержимое её почти всегда нужно уточнить:
 * `role="dialog"` для окна с формой, `role="menu"` для меню, `role="listbox"`
 * для списка вариантов. Роль передаётся обычным пропом.
 */
export type PopoverProps = Omit<ComponentPropsWithRef<'div'>, 'id' | 'popover'> & PopoverOwnProps;
