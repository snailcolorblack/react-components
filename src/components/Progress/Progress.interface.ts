// Progress.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/**
 * Каким показан ход дела.
 *
 * `LINE` — полоса во всю ширину места: привычное «сколько осталось»
 * под формой, в списке, в шапке карточки.
 *
 * `CIRCLE` — кольцо фиксированного размера. Берут там, где ширины нет
 * вовсе: в кнопке, в плитке, рядом с аватаром.
 */
export type ProgressVariant = 'LINE' | 'CIRCLE';

interface ProgressOwnProps {
    /** Полосой или кольцом. По умолчанию полосой. */
    variant?: ProgressVariant
    /**
     * Сколько сделано. Не передан — ход дела неизвестен, и показывается
     * бегущая полоса (кольцо — вращающейся дугой). Это не выдумка
     * компонента: `<progress>` без value именно так и устроен, его состояние
     * ловится псевдоклассом `:indeterminate`, и в дереве доступности
     * значение просто отсутствует (замерено).
     *
     * Единицы — ваши: шкалу задаёт `max`.
     */
    value?: number
    /**
     * Верх шкалы. По умолчанию 1, как у нативного `<progress>`: значит,
     * `value` — это доля. Для процентов передайте `max={100}`.
     */
    max?: number
    /**
     * Имя индикатора для скринридера: «Загрузка файла», «Заполнение
     * анкеты». У `<progress>` своего имени нет — замерено, в дереве
     * доступности у него роль `progressbar`, значение и пустое имя.
     *
     * Если подпись уже есть в разметке, вместо этого свяжите с ней через
     * `aria-labelledby` — текст не придётся повторять.
     */
    label?: string
    /**
     * Показать подпись не только скринридеру, но и глазами, над полосой.
     * Без него `label` остаётся только в дереве доступности.
     */
    showLabel?: boolean
    /**
     * Чем подписать значение: `format={(value, max) => `${value} из ${max}`}`.
     * У кольца число встаёт в середину, у полосы — справа от подписи.
     *
     * Текст помечен `aria-hidden`: значение уже объявлено самим
     * индикатором, и без этого скринридер читал бы его дважды.
     *
     * В неопределённом состоянии не вызывается — показывать нечего.
     */
    format?: (value: number, max: number) => ReactNode
}

/**
 * Ход дела: полоса или кольцо, заполняющиеся по мере выполнения.
 *
 *     <Progress label="Загрузка файла" value={0.4}/>
 *     <Progress label="Загрузка файла" variant="CIRCLE" value={40} max={100}
 *               format={value => `${value}%`}/>
 *     <Progress label="Идёт обработка"/>
 *
 * Под компонентом нативный `<progress>`: роль, значение, границы шкалы
 * и неопределённое состояние приходят от платформы, а не проставляются
 * руками. Рисует заливку обычный фон — один и тот же приём на оба вида,
 * без вендорных псевдоэлементов: линейная заливка у полосы, коническая
 * у кольца.
 *
 * Управлять видом снаружи — переменными на самом компоненте:
 *
 * | Переменная               | Что меняет                             | По умолчанию |
 * |--------------------------|----------------------------------------|--------------|
 * | `--progress-fill`        | цвет заполненной части                  | акцентный    |
 * | `--progress-track`       | цвет дорожки                            | контраст 10% |
 * | `--progress-thickness`   | толщина полосы и кольца                 | `2px`        |
 * | `--progress-size`        | длина полосы, поперечник кольца         | `auto` / `4rem` |
 * | `--progress-min`         | уже этого полоса не ужимается           | `10rem`      |
 * | `--progress-duration`    | за сколько заливка доезжает до значения | `0.3s`       |
 * | `--progress-cycle`       | оборот бегущей полосы и дуги            | `1.2s`       |
 *
 * `--progress-size: auto` у полосы значит «во всю ширину места». У кольца
 * auto не годится и потому не используется: замерено, с ним кольцо выходит
 * 21×21, а без числа внутри — вовсе 0×0, поэтому у кольца своё значение
 * по умолчанию. Переменная при этом одна на оба вида.
 *
 * `--progress-min` держит полосу там, где заполнять нечего: в родителе,
 * который сам сжимается по содержимому (`width: fit-content`,
 * `justify-items: center` у блока, элемент flex-строки без растяжения),
 * от неё иначе остаётся точка — замерено, 4×2px. Значение равно тому,
 * каким платформа рисует `<progress>` без стилей вовсе. В коробке уже
 * него полоса за неё выйдет; там опору снимают — `--progress-min: 0`.
 */
export type ProgressProps =
    Omit<ComponentPropsWithRef<'progress'>, 'value' | 'max' | 'children'>
    & ProgressOwnProps;
