/*                                                                            */
/*  Под компонентом нативный <progress>. Замерено в Chromium 141, что он      */
/*  отдаёт сам: роль progressbar, значение, границы шкалы (valuemin 0,        */
/*  valuemax из max) и неопределённое состояние — у <progress> без value      */
/*  в дереве доступности значения просто нет, а в CSS он ловится              */
/*  псевдоклассом :indeterminate.                                             */
/*                                                                            */
/*  Своего кода здесь поэтому почти нет: ни aria-valuenow, ни пересчёта       */
/*  процентов, ни обработчиков. Компонент только раскладывает подпись         */
/*  с числом и отдаёт долю в CSS переменной.                                  */
/* -------------------------------------------------------------------------- */

/* --- Как пишется ---------------------------------------------------------- */
/*
 *  <Progress label="Загрузка файла" value={0.4}/>
 *
 *  Шкала по умолчанию от 0 до 1, как у нативного <progress>. Проценты —
 *  это max={100}:
 *
 *  <Progress label="Загрузка файла" value={40} max={100}
 *            format={value => `${value}%`}/>
 *
 *  Без value ход дела неизвестен: полоса бежит, кольцо вращается.
 *
 *  <Progress label="Идёт обработка"/>
 */

/* --- Что делает браузер, а что мы ----------------------------------------- */
/*
 *  Браузер:
 *      роль, значение, границы шкалы, неопределённое состояние и его
 *      псевдокласс, обрезка значения к шкале.
 *
 *  CSS:
 *      заливка — обычный фон элемента, а не ::-webkit-progress-value:
 *      у полосы линейный градиент, у кольца конический с маской.
 *      Один приём на оба вида и ни одного вендорного псевдоэлемента
 *      в рисунке (они только гасятся, чтобы не закрывать фон).
 *
 *      Доля едет к новому значению сама: --progress объявлена через
 *      @property, а значит участвует в переходах. Замерено — 0.4 → 0.9
 *      прошло кадрами 0.53, 0.68, 0.80, 0.88, 0.9, без единой перерисовки
 *      React.
 *
 *      Своя анимация неопределённого состояния здесь не прихоть:
 *      замерено, что с appearance: none Chromium перестаёт рисовать
 *      бегущую полосу вовсе и показывает пустую дорожку.
 *
 *  Мы:
 *      раскладка подписи и числа да одна переменная с долей.
 */

/* --- Почему доля приходит из JS, а не из разметки ------------------------- */
/*
 *  Значение уже написано в атрибуте value, и CSS умеет его прочесть:
 *  замерено в Chromium 141, что calc(attr(value type(<number>)) * 1turn)
 *  при value="0.4" даёт ровно 144deg, и кольцо рисуется без единой строчки
 *  JS. Но типизированный attr() сегодня есть только в Chromium, а запасным
 *  путём всё равно была бы переменная. Держать два пути ради одного движка
 *  дороже, чем поставить переменную всем: она одна и меняется вместе
 *  с value.
 */

/* --- Имя обязательно ------------------------------------------------------ */
/*
 *  У <progress> своего имени нет — замерено, роль есть, значение есть,
 *  имя пустое. Безымянный индикатор скринридер объявит как «progress bar»
 *  и ничего не скажет о том, что именно идёт. Поэтому нужен label или
 *  aria-labelledby; если нет ни того, ни другого, в разработке компонент
 *  ругнётся в консоль.
 */
/* -------------------------------------------------------------------------- */

import {useEffect, useId, type CSSProperties} from 'react';
import type {ProgressProps, ProgressVariant} from './Progress.interface.ts';
import styles from './Progress.module.css';

const VARIANT_CLASS = {
    LINE: styles.line,
    CIRCLE: styles.circle,
} satisfies Record<ProgressVariant, string>;

function Progress({
                      variant = 'LINE',
                      value,
                      max = 1,
                      label,
                      showLabel = false,
                      format,
                      id,
                      className = '',
                      style,
                      ...props
                  }: ProgressProps) {

    const generatedId = useId();

    const known = value !== undefined;
    const labelId = `${id ?? generatedId}-label`;
    const named = label !== undefined || props['aria-labelledby'] !== undefined
        || props['aria-label'] !== undefined;
    /*
     * Доля для заливки. Обрезается здесь, а не в CSS: значение за шкалой
     * нарисовало бы кольцо больше полного оборота, а полосу — шире себя.
     * Самому <progress> обрезка не нужна, он делает её по спецификации.
     */
    const part = known && max > 0 ? Math.min(Math.max(value / max, 0), 1) : 0;

    /*
     * Проверка только в разработке: в сборке ветка вырезается целиком.
     * Условие смотрит на пропсы, а не на DOM, — имя может прийти и через
     * aria-labelledby на элемент, которого в этот момент ещё нет.
     */
    useEffect(() => {
        if (!import.meta.env.DEV || named) return;

        console.warn(
            'Progress: индикатор без имени. Скринридер объявит его просто '
            + '«progress bar» и не скажет, что именно идёт. Передайте label '
            + 'или aria-labelledby.',
        );
    }, [named]);

    return (
        <div
            className={[styles.progress, VARIANT_CLASS[variant], className].filter(Boolean).join(' ')}
            style={style}
        >
            {/*
              * Подпись и число лежат в одной строке у полосы и друг на друге
              * у кольца — раскладкой занимается CSS, разметка у обоих видов
              * одна.
              */}
            {label !== undefined && (
                /*
                 * Спрятана она или нет, из дерева доступности подпись
                 * не убирается: на неё ссылается aria-labelledby, и имя
                 * индикатора берётся именно отсюда. Поэтому атрибут свой,
                 * а не aria-hidden.
                 */
                <span id={labelId} className={styles.label} data-hidden={showLabel ? undefined : ''}>
                    {label}
                </span>
            )}

            {/*
              * Число помечено aria-hidden: значение уже объявлено самим
              * индикатором, и без этого скринридер прочитал бы его дважды.
              * Неопределённому ходу дела показывать нечего.
              */}
            {format !== undefined && known && (
                <span className={styles.value} aria-hidden="true">{format(value, max)}</span>
            )}

            <progress
                {...props}
                id={id}
                /*
                 * value без значения не ставится вовсе: именно его
                 * отсутствие и означает «сколько осталось — неизвестно».
                 * undefined React в разметку не пишет.
                 */
                value={value}
                max={max}
                aria-labelledby={label !== undefined ? labelId : props['aria-labelledby']}
                className={styles.bar}
                /*
                 * Не --progress, а --progress-to: по ней CSS и считает долю.
                 * Инлайновый стиль сильнее объявлений автора, и если писать
                 * сюда саму долю, @starting-style в стилях перестаёт
                 * действовать — заполнение не едет от нуля при появлении
                 * (замерено).
                 */
                style={known ? {'--progress-to': part} as CSSProperties : undefined}
            />
        </div>
    );
}

export {Progress};
