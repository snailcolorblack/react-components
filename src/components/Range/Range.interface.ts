// Range.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/**
 * Точка на шкале.
 *
 * Числом — подписью станет само число. Объектом — когда подпись должна
 * отличаться от значения: `{value: 8, label: 'много'}`. Текстовая подпись
 * уходит не только под шкалу, но и в `aria-valuetext`, то есть скринридер
 * прочитает «много», а не «8».
 */
export type RangeMark = number | {value: number, label?: ReactNode};

interface RangeCommonProps {
    /**
     * Подпись. Обязательна: ползунок без имени в дереве доступности
     * остаётся безымянным — «ползунок, 50», и ничего больше.
     */
    label: ReactNode
    /** Начало шкалы. По умолчанию 0. */
    min?: number
    /** Конец шкалы. По умолчанию 100. */
    max?: number
    /**
     * Шаг. По умолчанию 1.
     *
     * Уходит в атрибут поля, поэтому шаг стрелок, Page Up/Down и притяжку
     * при перетаскивании считает браузер, а не мы. При `snap` шаг
     * не действует: значения берутся только из точек.
     */
    step?: number
    /**
     * Точки на шкале: засечки и подписи под ней.
     *
     * Сами по себе точки ничего не ограничивают — это разметка шкалы.
     * Чтобы значение к ним прилипало, нужен `snap`.
     *
     *     <Range label="Срок" min={0} max={10} marks={[2, 4, 8]}/>
     */
    marks?: readonly RangeMark[]
    /**
     * Прилипать только к точкам: допустимыми остаются `min`, все `marks`
     * и `max`, промежуточных значений нет вовсе.
     *
     *     <Range label="Срок" min={0} max={10} marks={[2, 4, 8]} snap/>
     *
     * Замерено: `<datalist>` в Chromium 141 рисует засечки, но значение
     * к ним не притягивает (перетаскивание на 33% шкалы 0–10 давало 3,
     * на 55% — 6), поэтому притяжка наша. Клавиатура при `snap` тоже наша:
     * стрелка шагает к соседней точке, а не на `step` — иначе на шкале
     * 0–10 с точками 2, 4, 8 шаг в единицу возвращал бы значение обратно
     * в ту же точку, и ползунок стоял бы на месте.
     */
    snap?: boolean
    /**
     * Имя поля в форме. У пары уходит дважды, младшим значением вперёд, —
     * `FormData.getAll(name)` вернёт оба; так же ведут себя `<select
     * multiple>` и группа флажков.
     */
    name?: string
    /** Выключить: поле выпадает из табуляции и не уходит в форму. */
    disabled?: boolean
    /**
     * Своя ошибка: ответ сервера или проверка по другим полям формы.
     *
     * Собственной проверки у ползунка нет и быть не может: значение всегда
     * лежит между `min` и `max`, пустым оно не бывает, поэтому `required`
     * на нём ничего не значит.
     */
    error?: ReactNode
    /**
     * Как показать число человеку: подпись у шарика, подписи точек
     * и `aria-valuetext`.
     *
     *     format={value => `${value} ₽`}
     */
    format?: (value: number) => string
}

interface RangeSingleOwnProps {
    /** Значение. Управляемый режим: меняется снаружи, в `onChange`. */
    value?: number
    /** Значение поначалу. По умолчанию `min`. */
    defaultValue?: number
    /** Значение изменилось. */
    onChange?: (value: number) => void
    /** Только у пары: имена двух шариков. */
    thumbs?: never
    /** Только у пары: наименьший промежуток между значениями. */
    minDifference?: never
}

interface RangePairOwnProps {
    /**
     * Пара значений, младшее вперёд. Массив — это и есть признак пары:
     * второй шарик появляется от типа значения, отдельного пропа нет.
     */
    value?: readonly [number, number]
    /** Пара поначалу. По умолчанию `[min, max]`. */
    defaultValue?: readonly [number, number]
    /** Значения изменились. */
    onChange?: (value: [number, number]) => void
    /**
     * Имена шариков: по ним человек понимает, какой из двух он сейчас
     * двигает. По умолчанию «от» и «до».
     *
     * Имя каждого шарика собирается из подписи и этого слова — «Цена от»,
     * «Цена до», — через `aria-labelledby` на два элемента сразу.
     */
    thumbs?: readonly [ReactNode, ReactNode]
    /**
     * Наименьший промежуток между «от» и «до». По умолчанию 0 — шарики
     * сходятся вплотную.
     *
     *     <Range label="Цена" min={0} max={1000} minDifference={100}/>
     *
     * Предел объявляется и в дереве доступности: `aria-valuemax`
     * младшего шарика становится на этот промежуток меньше значения
     * старшего, то есть скринридер называет ту же границу, в которую
     * упирается мышь.
     *
     * При `snap` шарик встаёт на ближайшую точку, которая промежуток
     * не нарушает, а не на ближайшую вообще: иначе притяжка возвращала бы
     * его за предел.
     *
     * Промежуток больше самой шкалы, как и значения, которые ему уже
     * не отвечают, компонент не исправляет: это не его дело — он только
     * не даёт нарушить предел новым движением.
     */
    minDifference?: number
}

export type RangeSingleProps = Omit<ComponentPropsWithRef<'div'>, 'onChange' | 'defaultValue'>
    & RangeCommonProps & RangeSingleOwnProps;

export type RangePairProps = Omit<ComponentPropsWithRef<'div'>, 'onChange' | 'defaultValue'>
    & RangeCommonProps & RangePairOwnProps;

/**
 * Ползунок: один шарик или пара «от — до».
 *
 *     <Range label="Громкость" min={0} max={120} step={10}/>
 *     <Range label="Срок" min={0} max={10} marks={[2, 4, 8]} snap/>
 *     <Range label="Цена" min={0} max={1000} value={[200, 800]} onChange={setPrice}/>
 *
 * Внутри настоящий `<input type="range">` — один или два. От этого даром
 * достаётся всё, что обычно пишут руками: роль `slider`, `aria-valuemin`,
 * `aria-valuemax` и `aria-valuenow`, стрелки, Home, End, Page Up/Down,
 * перетаскивание мышью, пальцем и пером, участие в форме и собственный
 * перевод на язык системы.
 *
 * Своей остаётся только картинка: Chromium 141 ещё не умеет ни
 * `appearance: base`, ни `::slider-thumb` (замерено), поэтому дорожка,
 * заливка и шарики рисуются обёрткой, а поля лежат поверх прозрачным
 * слоем ввода.
 *
 * Ширину ползунок берёт у контейнера. В контейнере, который сам считает
 * размер по содержимому (flex или grid без заданной ширины — например,
 * ячейка сторибука), он просит `--range-min`, по умолчанию 16rem: иначе
 * схлопнулся бы до ширины собственной подписи. В контейнере уже этого
 * значения спокойно сжимается — наружу не вылезает.
 *
 *     <Range style={{'--range-min': '24rem'}}/>
 *
 * У пары шарики упираются друг в друга силами самого браузера: предел
 * одного — текущее значение другого (`low.max = high.value`). Так же
 * советует APG, и в дереве доступности это видно — `aria-valuemax`
 * младшего равен значению старшего.
 */
export type RangeProps = RangeSingleProps | RangePairProps;
