// Scroll.interface.ts
import type {ComponentPropsWithRef, ElementType, ReactNode} from 'react';

/**
 * По какой оси лента прокручивается.
 *
 * Имена логические, а не «горизонтально» и «вертикально»: `inline` идёт
 * вдоль строки и в арабской вёрстке сама разворачивается справа налево,
 * `block` — сверху вниз.
 */
export type ScrollAxis = 'inline' | 'block';

/**
 * Как лента останавливается.
 *
 * `smooth` — свободно, где отпустили; `fixed` — прицепляясь к началу
 * элемента (`scroll-snap-type: mandatory`). У `fixed` один щелчок колеса
 * переносит ровно на один элемент, а не на сколько-то пикселей.
 */
export type ScrollMode = 'smooth' | 'fixed';

interface ScrollOwnProps {
    /**
     * Чем прокручивать: `div` по умолчанию, но подойдёт любой тег.
     *
     *     <Scroll as="ul">{items.map(item => <li key={item.id}>…</li>)}</Scroll>
     *
     * Лента ничего не знает о содержимом: роли и семантику приносит тот,
     * кто её ставит. Прицепляются к началу прямые дети — на них вешается
     * `scroll-snap-align`.
     */
    as?: ElementType
    /** По какой оси. По умолчанию вдоль строки. */
    axis?: ScrollAxis
    /** Свободно или с привязкой к элементам. По умолчанию свободно. */
    mode?: ScrollMode
    /**
     * Имя ленты. Нужно, когда до содержимого нельзя добраться иначе:
     * если внутри нет ни одного фокусируемого элемента, лента сама
     * становится остановкой табуляции, а остановке нужно имя.
     *
     * Лента из карточек-ссылок имя не требует: по ней ходят через сами
     * карточки.
     */
    label?: ReactNode
    /**
     * Держать прокрутку в себе, не отдавая странице на краю.
     *
     * По умолчанию выключено, и это важнее, чем кажется: лента во всю
     * ширину с удержанием превращается в ловушку — колесо над ней
     * перестаёт листать страницу вовсе. Включать стоит там, где лента
     * занимает почти весь экран и мимо неё колесу всё равно не попасть.
     */
    trap?: boolean
    /**
     * Растушёвка у краёв: содержимое растворяется там, где лента
     * продолжается.
     *
     * Показывается только с той стороны, где есть продолжение: у начала
     * непрокрученной ленты её нет. Ведёт растушёвку сама прокрутка —
     * обработчика нет, перерисовок нет.
     */
    fade?: boolean
    /**
     * Кнопки-стрелки у краёв.
     *
     * Это `::scroll-button()` — кнопки самого браузера: он делает их
     * настоящими кнопками в дереве доступности, сам выключает крайнюю
     * и сам листает (замерено — шаг 500px при ленте 572, то есть почти
     * экран). Своего кода здесь нет вовсе.
     *
     * Движки, которые их ещё не умеют, просто не покажут ничего: лента
     * останется прокручиваемой всеми прочими способами. Имена кнопок
     * меняются переменными `--scroll-arrow-start-label`
     * и `--scroll-arrow-end-label`.
     */
    arrows?: boolean
    /**
     * Выйти за отступы родителя, оставив их первому и последнему элементу.
     *
     *     <div style={{padding: 32}}>
     *         <Scroll bleed>…</Scroll>
     *     </div>
     *
     * `true` — снять отступ с родителя один раз при отрисовке; строка —
     * взять указанное значение и не измерять ничего.
     *
     * Замер разовый, наблюдателя за размером нет: при смене вёрстки
     * по медиавыражению значение останется прежним — там, где отступ
     * меняется, лучше передать его строкой.
     */
    bleed?: boolean | string
    /**
     * Показывать полосу прокрутки. По умолчанию да.
     *
     * Прятать её стоит только вместе с `fade` или `arrows`: полоса —
     * единственный постоянный признак того, что лента едет, и без неё
     * с мышью без колеса остаётся только гадать. Сама прокрутка никуда
     * не девается: колесо, палец, трекпад и клавиши работают как прежде.
     */
    bar?: boolean
}

/**
 * Лента с прокруткой: обычный блок с `overflow`, а не самодельный виджет.
 *
 *     <Scroll label="Категории">{cards}</Scroll>
 *     <Scroll mode="fixed" as="ul">{slides}</Scroll>
 *     <Scroll axis="block" mode="fixed">{rows}</Scroll>
 *
 * Прокрутку, инерцию, полосу, жесты трекпада и пальца, клавиши и привязку
 * к элементам делает браузер. Свой здесь только перехват колеса: Chromium
 * не переводит вертикальное колесо в горизонтальную прокрутку — замерено,
 * лента стоит, уезжает страница. Слушатель непассивный, потому что React
 * вешает `wheel` пассивно и `preventDefault()` в нём не действует
 * (замерено — страница уехала на 41px).
 *
 * Клавиатура: если внутри ленты нет ничего фокусируемого, лента получает
 * `tabindex="0"` и становится доступной стрелками — иначе до её содержимого
 * с клавиатуры не добраться вовсе (WCAG 2.1.1). Если фокусируемые внутри
 * есть, лишняя остановка не нужна: браузер прокручивает ленту сам, ведя
 * фокус по карточкам.
 */
export type ScrollProps<T extends ElementType = 'div'> =
    ScrollOwnProps & Omit<ComponentPropsWithRef<T>, keyof ScrollOwnProps>;
