// Select.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/**
 * Сколько значений можно выбрать.
 *
 * `single` — один, `multi` — несколько. Разметка у них одна и та же:
 * кнопка `role="combobox"` и список `role="listbox"` по паттерну combobox
 * из APG. Отличий ровно три — выбор заменяет предыдущий или добавляется
 * к нему, список закрывается после выбора или нет, и в форму уходит одно
 * скрытое поле или по одному на значение.
 *
 * Нативного `<select>` под `single` нет намеренно. Он умеет всё сам,
 * но стилизуется только через `appearance: base-select`, то есть пока
 * лишь в Chromium: без него нельзя поменять ни скругления, ни отступы,
 * ни цвета, ни размеры. Вдобавок `::selectedcontent` не поддержан даже
 * там, из-за чего выбранный пункт в закрытом поле рисовался одним
 * слипшимся текстом. Для `multi` нативного варианта нет вовсе:
 * `<select multiple>` — прокручиваемая лента, а не раскрывающийся список
 * (замерено — роль `listbox`, не `combobox`).
 *
 * Цена отказа: клавиатуру, участие в форме и родной пикер на телефоне
 * компонент делает сам.
 */
export type SelectVariant = 'single' | 'multi';

/**
 * Как достать что-то из элемента списка: имя ключа или функция.
 *
 * Для простого массива строк или чисел не нужно ни то, ни другое —
 * элемент сам себе и подпись, и значение.
 */
export type SelectAccessor<T, R> = (keyof T & string) | ((item: T) => R);

interface SelectOwnProps<T> {
    /** Элементы списка. Строки, числа или объекты — что угодно. */
    items: readonly T[]
    /**
     * Подпись поля. Она же плавающий label: пока ничего не выбрано, стоит
     * по центру поля вместо подсказки, а с появлением значения уезжает
     * наверх.
     *
     * Это именно подпись, а не placeholder: она остаётся на месте после
     * выбора, поэтому пользователь всегда видит, что это за поле, —
     * требование WCAG 3.3.2, которое обычный placeholder нарушает.
     */
    label?: ReactNode
    /** Один или несколько. По умолчанию один. */
    variant?: SelectVariant
    /**
     * Что показывать как подпись элемента: имя ключа объекта или функция.
     *
     *     itemLabel="visibleName"
     *     itemLabel={item => `${item.name} (${item.count})`}
     *
     * Без него подписью становится сам элемент — годится для массива строк.
     * Отсюда же берётся имя пункта для скринридера и подпись чипса
     * у `multi`, поэтому подпись должна быть текстом, а не разметкой.
     */
    itemLabel?: SelectAccessor<T, ReactNode>
    /**
     * Что уйдёт в значение: имя ключа или функция. Без него значением
     * становится сам элемент.
     */
    itemValue?: SelectAccessor<T, string | number>
    /**
     * Разметка пункта в списке — иконка, второй строкой цена, что угодно.
     *
     *     itemRender={item => <><Icon name={item.icon}/> {item.visibleName}</>}
     *
     * Именем пункта для скринридера становится его содержимое, то есть
     * то, что вернула эта функция. Декоративное помечайте `aria-hidden`
     * сами — иначе иконка попадёт в озвучку:
     *
     *     itemRender={item => <><span aria-hidden="true">★</span>{item.name}</>}
     *
     * Разметка работает и в списке, и в закрытом поле у `single`: пункты
     * рисует компонент, а не системный пикер, поэтому отступы, иконки
     * и вторая строка доходят всюду. Ограничение нативного `<select>`,
     * где закрытое поле показывало один слипшийся текст, больше
     * не действует.
     */
    itemRender?: (item: T) => ReactNode
    /**
     * Текстовое имя элемента для скринридера: имя ключа или функция.
     *
     *     itemText="name"
     *     itemText={item => `${item.name}, ${item.count} шт.`}
     *
     * Нужен там, где подпись — разметка: именем кнопки может быть только
     * текст, а `<img>` внутри `itemLabel` текстом не является. Без него
     * имя берётся из подписи, если она строка или число, а если и это
     * не так — из значения.
     *
     * Сейчас отсюда берётся имя чипса у `multi` («Убрать Рубль»).
     */
    itemText?: SelectAccessor<T, string>
    /** Недоступные элементы: имя ключа или функция. */
    itemDisabled?: SelectAccessor<T, boolean>
    /**
     * Разметка чипса у `multi` — то, что показано в поле после выбора.
     *
     *     chipRender={item => <><img src={item.flag} alt=""/>{item.code}</>}
     *
     * Отдельно от `itemRender` потому, что места у них разные: в списке
     * помещается иконка и вторая строка, в поле — короткий код. Без него
     * чипс показывает `itemLabel`.
     *
     * Содержимое чипса скрыто от скринридера (`aria-hidden`): имя кнопке
     * даёт `aria-label`, иначе «Рубль ×» читалось бы как имя вместе
     * с крестиком. Поэтому картинкам здесь нужен `alt=""`, а текстовое
     * имя задаётся через `itemText`.
     *
     * Отступы, скругление и фон чипса меняются переменными, без
     * перекрытия классов:
     *
     *     .myField {
     *         --select-chip-padding: 2px 8px;
     *         --select-chip-radius: 4px;
     *     }
     */
    chipRender?: (item: T) => ReactNode
    /**
     * Имя поля в форме.
     *
     * На каждое выбранное значение рендерится своё скрытое поле с этим
     * именем, поэтому `FormData.getAll(name)` вернёт массив — так же
     * ведут себя нативный `<select multiple>` и группа флажков.
     * У `single` в массиве всегда не больше одного значения.
     */
    name?: string
}

/** Пропсы варианта с одним значением. */
export interface SelectSingleProps<T> extends SelectOwnProps<T> {
    variant?: 'single'
    value?: string | number | null
    defaultValue?: string | number | null
    onChange?: (value: string | null, item: T | null) => void
}

/** Пропсы варианта с несколькими значениями. */
export interface SelectMultiProps<T> extends SelectOwnProps<T> {
    variant: 'multi'
    value?: ReadonlyArray<string | number>
    defaultValue?: ReadonlyArray<string | number>
    onChange?: (values: string[], items: T[]) => void
}

/**
 * Выбор из списка: одно значение или несколько.
 *
 *     <Select label="Вид депозита" items={['Надёжный', 'Детский']}/>
 *
 *     <Select
 *         label="Вид депозита"
 *         name="deposit"
 *         items={deposits}
 *         itemLabel="visibleName"
 *         itemValue="value"
 *         itemRender={item => <><Icon name={item.icon}/> {item.visibleName}</>}
 *     />
 *
 *     <Select variant="multi" label="Валюты" name="currency" items={currencies}
 *             itemLabel="code" itemValue="id"/>
 *
 * Печатать в поле нельзя: это выбор из списка, а не комбобокс
 * с автодополнением. Отсюда и разметка — триггер это кнопка, а не
 * текстовое поле, которое скринридер объявил бы полем ввода.
 *
 * Клавиатура: на кнопке Enter и пробел открывают список, фокус уходит
 * на выбранный пункт или на первый. В списке стрелки ходят по кругу,
 * Home и End к краям, Enter и пробел выбирают, Esc закрывает и возвращает
 * фокус на кнопку, Tab закрывает и уводит дальше по странице. Поиска
 * по первым буквам нет: по APG он необязателен.
 *
 * Остальные пропсы уходят на обёртку поля: `className`, `style`,
 * `data-атрибуты`, `ref`. `disabled` и `required` обёртка не понимает —
 * это не поле формы; недоступность отдельных пунктов задаётся через
 * `itemDisabled`.
 */
export type SelectProps<T> =
    Omit<ComponentPropsWithRef<'div'>, 'onChange' | 'defaultValue'>
    & (SelectSingleProps<T> | SelectMultiProps<T>);