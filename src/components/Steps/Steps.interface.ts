// Steps.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

/** Одно деление шкалы. */
export interface Step {
    /**
     * Ключ шага. Внутри `Flow` это имя шага процесса — по нему
     * шкала понимает, где человек сейчас, и по нему же переходит.
     */
    name?: string
    /** Подпись: «Личные данные». */
    label: ReactNode
    /** Пояснение под подписью: «ФИО, ИИН, телефон». */
    description?: ReactNode
    /**
     * Значок вместо номера у этого шага. Общий для всех задаётся
     * пропом `ident`, этот сильнее.
     */
    icon?: ReactNode
    /**
     * На шаге ошибка. Отметка видна и в кружке (свой силуэт, а не
     * один цвет — WCAG 1.4.1), и в тексте для скринридера.
     *
     * Строка или узел — это ещё и пояснение под подписью: оно
     * вытесняет `description`, потому что ошибка важнее.
     */
    error?: boolean | ReactNode
    /** Шаг недоступен для перехода, даже когда шкала нажимаемая. */
    disabled?: boolean
}

/** Как шкала стоит. */
export type StepsOrientation = 'HORIZONTAL' | 'VERTICAL';

/** Чем шаг кончился. По нему и рисуется кружок. */
export type StepState = 'done' | 'current' | 'next' | 'error';

interface StepsOwnProps {
    /**
     * Шаги по порядку. Внутри `<Flow>` можно не передавать вовсе:
     * шкала возьмёт видимые шаги процесса сама. Подписи к ним
     * задаются там же — полями `title` и `description` шага.
     */
    items?: Step[]
    /**
     * Номер текущего шага, считая от нуля. Внутри `Flow`
     * не передаётся: процесс знает его сам.
     */
    current?: number
    /**
     * Какие шаги считать пройденными. По умолчанию все, что левее
     * текущего. Внутри `Flow` — те, где человек уже был: процесс
     * помнит путь, а он не обязан быть прямым (пропущенные по
     * условию шаги в него не попадают).
     */
    done?: number[]
    orientation?: StepsOrientation
    /**
     * Что в кружке.
     *
     * `true` (по умолчанию) — номер шага.
     * Узел — он же у всех шагов (свой значок у шага сильнее).
     * `false` — кружков нет вовсе: шкала становится рядом полос,
     * как отметки историй. Подписи при этом остаются.
     */
    ident?: boolean | ReactNode
    /**
     * Что рисовать у пройденного шага вместо номера. По умолчанию
     * галочка: пройденный шаг узнаётся силуэтом, а не только цветом.
     * `false` — оставить номер.
     */
    doneIcon?: ReactNode | false
    /** Нажимаемые ли шаги. По умолчанию — только если есть `onStepClick`. */
    clickable?: boolean
    /**
     * Щёлкнули по шагу. Приходит только для пройденных и текущего:
     * вперёд по шкале не ходят, туда ведёт кнопка «Дальше».
     *
     * Внутри `Flow` с `clickable` обработчик не нужен — шкала сама
     * зовёт `goToStep`.
     */
    onStepClick?: (index: number, step: Step) => void
    /** Имя шкалы для скринридера. По умолчанию «Шаги». */
    label?: string
    /** Подписи состояний: их читает скринридер, глазами они не видны. */
    labels?: Partial<StepsLabels>
}

export interface StepsLabels {
    /** «Шаг 2 из 5» — читается у каждого деления. */
    step: (index: number, total: number) => string
    done: string
    current: string
    error: string
}

/**
 * Шкала шагов: где человек сейчас, что уже позади и сколько осталось.
 *
 *     <Steps current={2} items={[
 *         {label: 'Личные данные', description: 'ФИО, ИИН, телефон'},
 *         {label: 'Доход', description: 'Работодатель и зарплата'},
 *         {label: 'Документы', description: 'Удостоверение и справка'},
 *         {label: 'Подписание', description: 'Подтверждение по SMS'},
 *     ]}/>
 *
 * Это `<ol>` со списком: порядок делений значим, и скринридер объявит,
 * сколько их всего. Текущий помечен `aria-current="step"` — отдельного
 * aria-состояния для «вы здесь» не существует. Кружок для скринридера
 * спрятан: номер и галочка — рисунок, а состояние приходит словом.
 *
 * Внутри `<Flow>` шкала работает без пропсов вовсе: берёт видимые шаги,
 * текущий и пройденный путь у процесса. Подписи шагов задаются там же:
 *
 *     {name: 'city', component: City, title: 'Город', description: 'Где вы живёте'}
 *
 * Переменные на коробке:
 *
 * | Переменная            | Что меняет                        |
 * |-----------------------|-----------------------------------|
 * | `--steps-size`        | сторона кружка                    |
 * | `--steps-line`        | толщина линии между делениями     |
 * | `--steps-gap`         | зазор между делением и подписью   |
 * | `--steps-done`        | цвет пройденного                  |
 * | `--steps-current`     | цвет текущего                     |
 * | `--steps-next`        | цвет будущего                     |
 * | `--steps-error`       | цвет ошибки                       |
 */
export type StepsProps =
    Omit<ComponentPropsWithRef<'ol'>, 'children'>
    & StepsOwnProps;
