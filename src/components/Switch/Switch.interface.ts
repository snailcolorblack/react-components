// Switch.interface.ts
import type {ComponentPropsWithRef, ReactNode} from 'react';

interface SwitchOwnProps {
    /**
     * Подпись. Может быть разметкой — текст, картинка, несколько строк.
     *
     * Интерактива внутри быть не должно: обёртка это сам `<label>`,
     * и клик по вложенной ссылке или кнопке уйдёт переключателю.
     * Нужна ссылка рядом — выносите её за пределы компонента.
     */
    children?: ReactNode
}

/**
 * Свитч — включатель одной настройки, а не выбор из списка.
 *
 * Внутри самый обычный `<input type="checkbox">`: свитч не выбирает вариант,
 * а включает и выключает ровно одну вещь, и по состоянию (checked/unchecked,
 * форма, `defaultChecked`/`checked`) это чекбокс и есть. Отличие только
 * в роли и в том, как это читает скринридер, — про это `role="switch"` ниже.
 *
 * `className` и `style` попадают на обёртку `<label>`, где живут оформление
 * и переменные цвета. Всё остальное идёт на сам `<input>`: `name`, `value`,
 * `checked`, `defaultChecked`, `onChange`, `disabled`, `required`, `form`.
 * Туда же `ref` — он указывает на поле, а не на обёртку.
 *
 *     <Switch name="notify" defaultChecked>Уведомления</Switch>
 *     <Switch checked={dark} onChange={e => setDark(e.target.checked)}>
 *         Тёмная тема
 *     </Switch>
 *
 * `role` компонент ставит сам и не даёт перебить: без него скринридер
 * прочитает «флажок, отмечено», хотя настройка включена сразу, без отправки
 * формы, и правильное объявление — «переключатель, включено». Есть нативный
 * HTML-атрибут `switch` с тем же эффектом, но по состоянию на начало 2026-го
 * его понимает только Safari 17.4+ — остальные молча его игнорируют
 * и показывают обычный чекбокс. `role="switch"` работает везде уже сейчас,
 * поэтому здесь он, а не атрибут.
 *
 * Индикатора «выполняется» у свитча нет: настройка либо включена, либо нет,
 * без промежуточного «применяется» — в отличие от `Button` с его `loading`,
 * которому есть что показывать между кликом и ответом сервера.
 */
export type SwitchProps = Omit<ComponentPropsWithRef<'input'>, 'type' | 'children' | 'role'> & SwitchOwnProps;
