// Tabs.context.ts

/* -------------------------------------------------------------------------- */
/*  СВЯЗЬ МЕЖДУ БЛОКАМИ                                                       */
/*                                                                            */
/*  Кнопки и панели лежат в разных местах разметки, а знать друг о друге      */
/*  обязаны: у кнопки aria-controls на панель, у панели aria-labelledby       */
/*  на кнопку, и обе смотрят на одно и то же активное значение.               */
/*                                                                            */
/*  Нативных табов в HTML нет, поэтому «нативного» способа связать эти два    */
/*  блока тоже нет — выбор только между контекстом, разбором children через   */
/*  cloneElement и состоянием, вынесенным в DOM. Разбор children молча        */
/*  ломается, стоит обернуть блок во что-нибудь ещё; состояние в DOM убирает  */
/*  две перерисовки ценой того, что вся ARIA уезжает из разметки              */
/*  в обработчик. Контекст здесь дешевле: на переключение перерисовываются    */
/*  ровно два потребителя, и меньше не выйдет — у кнопок меняется             */
/*  aria-selected, у панелей видимость.                                       */
/* -------------------------------------------------------------------------- */

import {createContext, use} from 'react';
import type {TabsOrientation, TabsVariant} from './Tabs.interface.ts';

export interface TabsState {
    /** Основа для id кнопок и панелей: из неё строятся обе связи. */
    base: string
    /** Значение открытой вкладки. */
    active: string
    /** Куда смотрят стрелки. */
    orientation: TabsOrientation
    /** Вид: полоса с подчёркиванием или группа кнопок. */
    variant: TabsVariant
    /** Открыть вкладку. */
    select: (value: string) => void
}

export const TabsContext = createContext<TabsState | null>(null);

/**
 * Состояние вкладок для внутренних блоков.
 *
 * Бросает исключение снаружи `<Tabs>`: без контекста блок не может ни
 * построить id, ни узнать, открыт он или нет, и молча отрисовал бы
 * разметку, в которой aria-связи указывают в пустоту.
 */
export function useTabs(who: string) {
    const state = use(TabsContext);

    if (state === null) throw new Error(`${who} должен лежать внутри <Tabs>`);

    return state;
}

/**
 * Значение в кусок id. Пробелы и всё, что не буква и не цифра, уходят:
 * `aria-controls` это IDREF, пробел в нём разделяет ссылки, а не входит
 * в имя.
 */
export function slug(value: string) {
    return value.replace(/[^\w-]/g, '-');
}
