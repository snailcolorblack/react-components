// Toast.interface.ts
import type {ReactNode} from 'react';
import type {AlertVariant} from '../Alert/Alert.interface.ts';

/**
 * Угол экрана, в котором появляются сообщения.
 *
 * Логические, а не левый-правый: START и END переворачиваются вместе
 * с направлением письма, поэтому в арабской вёрстке ничего править
 * не нужно.
 */
export type ToastPosition =
    | 'TOP_START' | 'TOP_CENTER' | 'TOP_END'
    | 'BOTTOM_START' | 'BOTTOM_CENTER' | 'BOTTOM_END';

/** Чем одно сообщение отличается от остальных в этой же области. */
export interface ToastOptions {
    /** Вариант плашки: цвет и тон иконки. Тот же, что у Alert. */
    variant?: AlertVariant
    /**
     * Иконка слева от текста. Скрыта от скринридера: смысл несёт текст,
     * а «галочка Сохранено» в озвучке — лишнее слово. Прямой `<svg>`
     * красится тоном варианта автоматически.
     */
    icon?: ReactNode
    /**
     * Через сколько миллисекунд закрыть само. Без него берётся `duration`
     * области, `0` — не закрывать вовсе.
     */
    duration?: number
}

/**
 * Управление сообщениями. Приходит через `ref` — так же, как
 * `showModal()` у `<dialog>` и `showPopover()` у поповера.
 *
 * Метод здесь один, и это не забывчивость: закрывать сообщение снаружи
 * нельзя. Оно уходит само по таймеру или по крестику — то есть тогда,
 * когда его прочитали или когда читать перестали. Код, который показал
 * сообщение, к этому моменту уже давно отработал и знать, когда его
 * пора убирать, не может.
 */
export interface ToastHandle {
    /**
     * Показать сообщение.
     *
     *     toastRef.current?.show('Сохранено');
     *     toastRef.current?.show(`Ошибка ${response.status}: не удалось сохранить`,
     *                            {variant: 'ERROR'});
     *
     * Каждый вызов добавляет ещё одну плашку: четыре ошибки — четыре
     * сообщения, а не одно поверх другого. Они складываются столбиком
     * в своей области, и у каждой свой таймер.
     */
    show(content: ReactNode, options?: ToastOptions): void
}

/**
 * Область всплывающих сообщений.
 *
 *     const toastRef = useRef<ToastHandle>(null);
 *
 *     <Toast ref={toastRef} position="TOP_END"/>
 *
 *     if (!response.ok) {
 *         toastRef.current?.show(`Ошибка ${response.status}: не удалось сохранить`,
 *                                {variant: 'ERROR'});
 *     }
 *
 * Компонент монтируется один раз и ничего не рисует на месте: плашки
 * уходят в верхний слой, в область своего угла. Очередь он держит сам,
 * поэтому «четыре ошибки — четыре сообщения» работает без списка
 * снаружи.
 *
 * Движение здесь одностороннее: снаружи сообщение только показывают,
 * а закрывает его сама плашка — крестиком или таймером. Поэтому у ручки
 * нет ни hide, ни clear, и состояние очереди наружу не протекает.
 *
 * ЧТО СЮДА КЛАСТЬ, А ЧТО НЕТ
 *
 * Тост — для того, что можно не прочитать: «Сохранено», «Копия создана»,
 * «Не удалось синхронизировать, попробуем позже». Он исчезает сам,
 * поэтому всё, без чего нельзя продолжить, ему доверять нельзя.
 *
 * Ошибки полей формы сюда не кладут, даже если их четыре. По WCAG 3.3.1
 * сообщение об ошибке должно быть рядом с тем полем, где ошибка, —
 * для этого есть `<Alert live variant="ERROR">` под полем. Столбик
 * из четырёх исчезающих плашек вдобавок требует прочитать их все
 * за пять секунд и не говорит, куда смотреть.
 *
 * Несколько сообщений сразу оправданы, когда события действительно
 * разные и независимые: пришли три ответа от бэкенда, два файла
 * загрузились, а третий нет. Одно событие — одно сообщение; повторять
 * одно и то же на каждую неудачную попытку не нужно.
 *
 * Плашка внутри — это Alert, поэтому варианты, покраска иконки
 * и поведение в высоком контрасте у них общие.
 *
 * Область объявлена вежливым живым регионом (`aria-live="polite"`):
 * скринридер дочитает начатое и только потом прочтёт сообщение.
 * Для того, что требует реакции немедленно, тост — неподходящее место:
 * берите `<Alert live variant="ERROR">` в самой форме, он объявляется
 * assertive и не исчезает.
 *
 * Ограничение, которое стоит знать заранее: пока открыт МОДАЛЬНЫЙ диалог
 * (`showModal`), всё вне него становится inert. Сообщение при этом видно —
 * замерено в Chromium, оно рисуется поверх диалога, — но нажать крестик
 * нельзя, и скринридер его не получит: в дереве доступности при открытой
 * модалке ноль узлов области против одного после её закрытия. Поэтому
 * сообщение о том, что произошло внутри диалога, кладите в сам диалог.
 */
export interface ToastProps {
    /** Угол экрана. По умолчанию снизу в конце строки. */
    position?: ToastPosition
    /**
     * Сколько миллисекунд живёт сообщение, у которого нет своего
     * `duration`. По умолчанию 5000, `0` — не закрывать.
     *
     * Отсчёт замирает, пока на сообщении курсор или фокус, и продолжается
     * с того же места, когда они ушли: требование WCAG 2.2.1 — то, что
     * исчезает само, должно уметь остановиться. Вторая половина того же
     * требования — крестик, и он есть всегда.
     */
    duration?: number
    /** Подпись крестика для скринридера. По умолчанию «Закрыть». */
    closeLabel?: string
    /** Класс на каждую плашку области. */
    className?: string
    /** Управление очередью: `show`, `hide`, `clear`. */
    ref?: React.Ref<ToastHandle>
}

/** Одно сообщение в очереди области. */
export interface Item extends ToastOptions {
    id: number
    content: ReactNode
    closing?: boolean
}

/** Пропсы одной плашки: её место — внутри области, снаружи не создаётся. */
export interface PlateProps {
    item: Item
    duration: number
    closeLabel: string
    className: string
    onDismiss: () => void
}