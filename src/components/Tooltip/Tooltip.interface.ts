// Tooltip.interface.ts
import type {ComponentPropsWithRef, HTMLAttributes, ReactElement, ReactNode} from 'react';

/** С какой стороны триггера появляется подсказка. */
export type TooltipPlacement = 'block-start' | 'block-end' | 'inline-start' | 'inline-end';

/**
 * Чем подсказка приходится триггеру.
 *
 * `description` — уточнение к элементу, у которого имя уже есть: подпись
 * кнопки, метка поля. Скринридер читает его после имени.
 *
 * `label` — подсказка И ЕСТЬ имя: иконочная кнопка без текста. Тогда
 * собственный aria-label на триггере не нужен, иначе имя прочитается дважды.
 */
export type TooltipMode = 'description' | 'label';

interface TooltipOwnProps {
    /**
     * Текст подсказки. Короткий и неинтерактивный: внутрь нельзя класть
     * кнопки и ссылки — до них не добраться, не нарушив правило «фокус
     * в подсказку не уходит».
     */
    text: ReactNode
    /**
     * Ровно один элемент-триггер. Он получит обработчики наведения и фокуса,
     * связь по aria и имя якоря, поэтому обязан пробрасывать пропсы на свой
     * DOM-узел — как это делают Button и любой элемент разметки.
     *
     * Тип нарочно не привязан к кнопке: триггером может быть ссылка,
     * иконка, поле ввода — что угодно, что принимает обработчики
     * и попадает в порядок фокуса.
     */
    children: ReactElement<HTMLAttributes<HTMLElement>>
    /** С какой стороны появляться. По умолчанию сверху. */
    placement?: TooltipPlacement
    /**
     * Задержка перед показом при наведении, мс. Нужна, чтобы подсказки
     * не мелькали, когда курсор просто проходит мимо. При появлении
     * по фокусу задержки нет: клавиатурный пользователь пришёл сюда
     * намеренно.
     */
    delay?: number
    /** Описание или имя. По умолчанию описание. */
    mode?: TooltipMode
}

/**
 * Подсказка — не поповер с другим триггером, а отдельный контракт.
 *
 * Поповер это самостоятельная область рядом с кнопкой; подсказка —
 * часть самой кнопки: триггер ссылается на неё через aria-describedby,
 * и скринридер читает её как продолжение имени. Отсюда три ограничения,
 * которых у поповера нет: открывается наведением и фокусом, а не кликом;
 * не содержит интерактива; никогда не забирает фокус.
 *
 * Подсказка недостижима на тач-устройствах — наведения там нет. Поэтому
 * в неё нельзя класть то, без чего задачу не выполнить: она уточняет
 * и напоминает, но не сообщает необходимое.
 */
export type TooltipProps = Omit<ComponentPropsWithRef<'div'>, 'children'> & TooltipOwnProps;
