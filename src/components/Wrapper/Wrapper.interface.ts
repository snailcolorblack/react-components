// Wrapper.interface.ts
import type {ComponentPropsWithRef, ElementType} from 'react';

/**
 * Оформление коробки.
 *
 * `CARD` — фон, скругление и отступы: самостоятельный блок содержимого.
 * `PLAIN` — только раскладка: коробка-контейнер без фона, отступов
 * и скругления. Нужна там, где блок группирует другие блоки, а своего
 * вида у него нет: вложенные карточки одна в другой читаются как
 * нагромождение слоёв.
 */
export type WrapperVariant = 'CARD' | 'PLAIN';

interface WrapperOwnProps<T extends ElementType> {
    /**
     * Каким тегом отрисоваться. По умолчанию `div`.
     *
     * Пропсы наследуются от выбранного тега: с `as="button"` появятся
     * `type` и `disabled`, с `as="a"` — `href`, с `as="form"` — `action`
     * и `method`. Своих ограничений обёртка не вводит.
     */
    as?: T
    variant?: WrapperVariant
}

/**
 * Обёртка: основной блок содержимого вместо голого `<div>`.
 *
 *     <Wrapper>Содержимое</Wrapper>
 *     <Wrapper as="article">Статья</Wrapper>
 *     <Wrapper as="form" action={save}>Поля</Wrapper>
 *     <Wrapper as="button" onClick={open}>Карточка-кнопка</Wrapper>
 *
 * Берёт на себя три вещи: отступы, скругление и фон из общих переменных;
 * собственные стили браузера у тега, которым она стала; и объявление
 * размерного контейнера, чтобы содержимое могло подстраиваться под
 * ширину блока, а не окна.
 *
 * Про собственные стили браузера стоит сказать отдельно: `<button>`
 * приходит со своим шрифтом, выравниванием по центру и рамкой,
 * `<fieldset>` — с рамкой и `min-inline-size: min-content`, из-за
 * которого он отказывается сжиматься в гибкой раскладке, а `<form>`
 * и `<figure>` — с внешними полями. Обёртка снимает это сама, иначе
 * один и тот же блок выглядел бы по-разному в зависимости от тега.
 *
 * Переменные на коробке:
 *
 * | Переменная          | Что меняет                    |
 * |---------------------|-------------------------------|
 * | `--wrapper-padding` | внутренние отступы            |
 * | `--wrapper-radius`  | скругление                    |
 * | `--wrapper-bg`      | фон                           |
 *
 * Отступ по умолчанию гибкий: `clamp(1rem, 3cqi, 2rem)`. Единица `cqi` —
 * доля ширины внешнего контейнера, а не окна: блок в узкой колонке
 * на широком экране получает узкий отступ, чего `vw` дать не может.
 * Где внешнего контейнера нет, `cqi` считается от окна, то есть ведёт
 * себя как `vw` — хуже не становится нигде.
 */
export type WrapperProps<T extends ElementType = 'div'> =
    WrapperOwnProps<T>
    & Omit<ComponentPropsWithRef<T>, 'as' | 'variant'>;
