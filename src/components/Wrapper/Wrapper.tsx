// Wrapper.tsx

/* -------------------------------------------------------------------------- */
/*  ОБЁРТКА                                                                   */
/*                                                                            */
/*  Основной блок содержимого вместо голого <div>. Отступы, скругление        */
/*  и фон приходят из общих переменных, поэтому блоки по всему приложению     */
/*  одинаковы, а не «почти одинаковы».                                        */
/*                                                                            */
/*  Своего состояния и своих обработчиков у неё нет вовсе: это коробка.       */
/* -------------------------------------------------------------------------- */

/* --- Почему полиморфная ---------------------------------------------------- */
/*
 *  Один и тот же блок бывает разделом, статьёй, формой и нажимаемой
 *  карточкой. Без `as` пришлось бы либо плодить обёртки под каждый тег,
 *  либо оставлять <div> там, где смысл требует <article> или <form>, —
 *  то есть терять разметку ради оформления.
 *
 *  Пропсы при этом наследуются от выбранного тега: `action` появляется
 *  только у формы, `href` — только у ссылки. Своих запретов обёртка
 *  не вводит: в отличие от Button, у неё нет поведения, которое
 *  с каким-то тегом не сочеталось бы.
 */

/* --- Что обёртка снимает с тегов ------------------------------------------ */
/*
 *  Замерено в Chromium 141, стили браузера по умолчанию:
 *
 *  <button>  — свой шрифт (13.333px Arial вместо унаследованного),
 *              выравнивание по центру, рамка и appearance: auto;
 *  <fieldset>— рамка в 2px groove и min-inline-size: min-content,
 *              из-за которого он не сжимается в гибкой раскладке;
 *  <form>    — внешнее поле снизу (margin-block-end: 1em в некоторых
 *              движках; в Chromium 141 — 0);
 *  <figure>  — внешние поля со всех сторон;
 *  <dialog>  — своя рамка и поля.
 *
 *  Всё это снимается в CSS обёртки. Иначе один и тот же блок выглядел бы
 *  по-разному в зависимости от того, каким тегом его отрисовали, и смысл
 *  полиморфности пропадал бы.
 */
/* -------------------------------------------------------------------------- */

import type {ElementType} from 'react';
import type {WrapperProps, WrapperVariant} from './Wrapper.interface.ts';
import styles from './Wrapper.module.css';

const VARIANT_CLASS = {
    CARD: styles.card,
    PLAIN: styles.plain,
} satisfies Record<WrapperVariant, string>;

function Wrapper<T extends ElementType = 'div'>(props: WrapperProps<T>) {
    const {
        as,
        variant = 'CARD',
        className = '',
        ...rest
        /* Пропсы тега здесь уже не различить: он выбирается во время
           работы, а тип — во время сборки. Разбираем как кнопку —
           у неё из нужных нам атрибутов есть всё. */
    } = props as WrapperProps<'button'> & {as?: ElementType};

    const Component = (as ?? 'div') as ElementType;
    /*
     * У <button> без type по умолчанию стоит submit: нажимаемая карточка
     * внутри формы отправляла бы её, ничего об этом не сообщая. Замерено —
     * атрибута type у обёртки нет вовсе, а значит действует подразумеваемый.
     * Переданный снаружи сильнее: type="submit" никто не запрещает.
     */
    const type = as === 'button' ? (rest.type ?? 'button') : rest.type;

    return (
        <Component
            {...rest}
            type={type}
            className={[styles.wrapper, VARIANT_CLASS[variant], className].filter(Boolean).join(' ')}
        />
    );
}

export {Wrapper};
