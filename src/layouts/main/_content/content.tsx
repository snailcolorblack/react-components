/* --- Почему страница рисуется только после первого открытия ---------------- */
/*
 *  Tabs держит в разметке ВСЕ панели: закрытые прячет hidden="until-found",
 *  чтобы поиск по странице (Ctrl+F) их находил и раскрывал. Для сторибука
 *  это значило бы, что lazy у всех страниц вызовется сразу на первой
 *  отрисовке — React запрашивает чанк там, где элемент отрисован, а не
 *  там, где он виден. Ленивость пропала бы целиком.
 *
 *  Поэтому у панели стоит lazy: решение принимает сам Tabs.Content,
 *  которому и так известно, открыта панель или нет. Снаружи вкладкам
 *  ничего держать не нужно — открытую вкладку Tabs ведёт сам.
 *
 *  Замерено в Chromium 141 на собранном приложении с двумя страницами.
 *  Без lazy на первой отрисовке запрашивались все четыре скрипта сразу:
 *  index.js, content.parts.js, Typography.component.js
 *  и Wrapper.component.js. С lazy — три, а Wrapper.component.js
 *  приходит только после нажатия на свою вкладку.
 *
 *  Открытая один раз панель больше не пустеет: состояние примеров
 *  переживает переключение, и поиск по ней работает.
 */
/* -------------------------------------------------------------------------- */

import {Suspense} from 'react';
import {Tabs} from 'component/Tabs/Tabs.tsx';
import {Typography} from 'component/Typography/Typography.tsx';
import type {ContentProps} from '../main.interface.ts';
import styles from './content.module.css';

export default function Content({pages}: ContentProps) {
    return (
        <>
            {Object.entries(pages).map(([name, Page]) => (
                <Tabs.Content key={name} value={name} lazy className={styles.page}>
                    <Suspense fallback={<Typography variant={'note'}>Загрузка…</Typography>}>
                        <Page/>
                    </Suspense>
                </Tabs.Content>
            ))}
        </>
    );
}
